def _indent(code, pad="    "):
    return "\n".join(pad + l for l in (code or "").splitlines() if l.strip())


def has_code(code):
    """Is this a real body, or a placeholder that is only a note to a human?

    An entry with no Csound must not be quoted as though it had some, and this used to
    ask whether the FIRST CHARACTER was `;` — which is a different question with a
    different answer the moment a body opens with a comment. Four beds (`rain`,
    `crackle`, `thunder`, `cymbal`) grew a leading `; MOVEMENT: TEXTURE` declaration and
    all four silently vanished from the page the author reads, while `render_index`
    went on listing them: named on the shelf, and then neither quoted nor listed. Their
    bodies have 8, 8, 8 and 35 lines of Csound.

    So the question is whether ANY line is code."""
    return any(l.strip() and not l.lstrip().startswith(";")
               for l in (code or "").splitlines())


# A library is LOOKED UP IN, not recited. The lexicon's `surface_forms` are the
# index built for exactly that — the words that reach an entry. They select what
# the author gets to READ; they decide nothing about the sound, because the
# author still writes whatever it writes and may depart from every suggestion.
# Reciting all 29 instruments, 51 words and 17 motions cost 60,000 characters on
# every bake, of which a given prompt needs a handful.
# `_` is part of a word here. Library keys carry underscores (`fm_stack`,
# `struck_bar`, `drum_head`), the index prints them that way, and that is how the
# author writes them back — so tokenising `fm_stack` into {fm, stack} would let
# the bare form `fm` claim a request for the DX7 chain and open `fm3` instead.
_WORD = re.compile(r"[a-zà-ÿ0-9'_]+")


def _index(lexicon_section):
    """surface form (and key) -> entry key."""
    idx = {}
    for e in lexicon_section:
        idx[e["key"].lower()] = e["key"]
        for sf in e.get("surface_forms", []):
            idx[str(sf).strip().lower()] = e["key"]
    return idx


def _lookup(text_in, index):
    """Entry keys whose surface forms appear in a text. Multi-word forms are
    matched against the raw text, single words against the tokenised text, so
    "electric piano" hits without "piano" alone dragging in a second entry.

    This is READING, never deciding. It used to be run on the USER's prompt, and
    what it found is what the author was then allowed to see — a word comparison
    standing between a person's description and the library, with a word
    matcher's holes in it ("bell" hits, "bells" does not, German nothing at all).
    It is now run on the AUTHOR's OWN reply, to find out which entries the author
    said it wanted. Understanding the prompt is the model's job; this only has to
    recognise the names the model itself wrote down."""
    text = " " + (text_in or "").lower() + " "
    # Each token twice: as written, and with any surrounding underscores taken
    # off. `_` has to be INSIDE a token so `fm_ep` cannot be read as the word
    # `fm` — and the moment it is, markdown emphasis swallows the word instead
    # (`_saw_` tokenises to `_saw_`, and 87 of the 98 keys, every one without an
    # underscore of its own, stopped being reachable when the author wrote them
    # that way). Stripping the outer underscores restores those without giving
    # `fm_ep` back to `fm`.
    words = set()
    for w in _WORD.findall(text):
        words.add(w)
        words.add(w.strip("_"))
    words.discard("")
    hits = []
    for form, key in index.items():
        if key in hits:
            continue
        # A form that is not a single bare word is matched against the raw text.
        # UNDERSCORES belong in this branch, and leaving them out was a hole with
        # teeth: `render_index` prints every entry by its key, so `struck_bar` is
        # exactly what the author writes when it asks for that entry — and
        # `_WORD` does not include `_`, so the form `struck_bar` was tested
        # against the tokens {struck, bar} and could never match. Six keys were
        # unreachable by their own printed name (`struck_bar`, `ring_mod`,
        # `analog_osc`, `open_up`), and two opened something ELSE: `fm_ep` and
        # `metallic_fm` tokenised to `fm` and opened the plain FM instrument.
        if " " in form or "-" in form or "_" in form:
            if form in text or form.replace("_", " ") in text:
                hits.append(key)
        elif form in words:
            hits.append(key)
    return hits


_index_cache = None


def _indexes():
    global _index_cache
    if _index_cache is None:
        with open(Path(__file__).resolve().parent / "dco_lexicon.json",
                  encoding="utf-8") as fh:
            lex = json.load(fh)
        _index_cache = tuple(_index(lex[s])
                             for s in ("techniques", "adjectives", "motions"))
    return _index_cache


def named_entries(text, lib=None):
    """Which library entries the AUTHOR's own reply asked to have opened.

    The author is shown the index (`render_index`) and reasons about the sound;
    whatever it names in that reasoning is what gets quoted to it in full. This
    function does not choose — it recognises names the model itself wrote down,
    over the same surface forms the lexicon already carries (so "bell" finds
    `fm_bell` and "electric piano" finds `ep_fm3`, whichever way the model said
    it).

    Nothing here is a fallback: naming nothing is a real answer, and the caller
    responds to it by opening the WHOLE library rather than by picking a set on
    the model's behalf."""
    lib = lib if lib is not None else _load_library()
    t_idx, a_idx, m_idx = _indexes()
    have = {s: {e["key"] for e in lib[s]}
            for s in ("instruments", "adjectives", "motions")}
    hits = {"instruments": _lookup(text, t_idx),
            "adjectives": _lookup(text, a_idx),
            "motions": _lookup(text, m_idx)}
    out = {s: [k for k in hits[s] if k in have[s]] for s in hits}
    # The forms are indexed from the LEXICON and matched against the LIBRARY, and an
    # entry can be in the first and deliberately withheld from the second (see
    # `lco_build_library.assemble`). Ten forms are in that state — `noise`,
    # `white noise`, `rauschen`, `pink noise`, `rosa rauschen` and five more — and the
    # drop used to be silent, so a reply naming "white noise" precisely was
    # indistinguishable in the trace from a reply that named no instrument at all.
    # Reported, not repaired: the entry really is unavailable, and the honest record is
    # that the author asked for something the library does not offer.
    out["withheld"] = sorted({k for s in hits for k in hits[s] if k not in have[s]})
    return out


def open_entries(named, lib=None):
    """The library pages the author asked for, in `render_library`'s shape.

    `named` is what `named_entries` recognised. Everything else stays LISTED but
    unquoted, so the author can still see what exists and ask for it in a later
    turn.

    NO INSTRUMENT recognised means everything is opened. Two different situations
    reach that state — the author named no instrument, or it named instruments
    this reader failed to recognise — and neither one tells Python which subset
    the author may see. Handing over adjectives and motions with no idiom under
    them, while the turn says "here are the entries you asked for", would be the
    one shape that is worse than opening too much: a writing turn that claims to
    answer a request it dropped. Keyed on instruments rather than on all three
    sections together because an orchestra is written out of an idiom; a reply
    that reached only the word `analog` inside `analog_osc` used to satisfy
    `any()` and open no instrument at all."""
    lib = lib if lib is not None else _load_library()
    named = named or {}
    sections = ("instruments", "adjectives", "motions")
    have = {s: {e["key"] for e in lib[s]} for s in sections}
    asked = {s: set(named.get(s) or ()) & have[s] for s in sections}
    wanted = dict(asked)
    if not wanted["instruments"]:
        wanted = dict(have)

    sel = {"catalogue": {}}
    for s in sections:
        sel[s] = [e for e in lib[s] if e["key"] in wanted[s]]
        sel["catalogue"][s] = [e for e in lib[s] if e["key"] not in wanted[s]]
    # BOTH halves of what happened, because they can differ and the difference is
    # the interesting fact: `named` is what the author asked for, `opened` what
    # was actually put in front of it. They part company exactly when the reply
    # named words and movements but no instrument — the panel would otherwise
    # have to infer "the author named nothing" from a full `opened`, and say that
    # over a reply that named three things.
    sel["consultation"] = {
        "named": {s: sorted(asked[s]) for s in sections},
        "opened": {s: sorted(wanted[s]) for s in sections},
        "library_size": sum(len(lib[s]) for s in sections),
        # The THIRD case `named`/`opened` alone cannot express: the author named an
        # entry that exists in the lexicon and is withheld from the library. Without
        # this, that reply looks exactly like one that named nothing.
        "named_withheld": sorted(named.get("withheld") or ()),
    }
    return sel


def _catalogue(out, lib, section, intro):
    """The shelf the author did not pull from — listed, so nothing is invisible.

    Redundant with the index in the system prompt and kept anyway: the writing
    turn is where the author is looking, and an entry it did not think of in the
    consultation is still nameable — it can write that idiom itself, or ask for
    it in a repair. The weight of the code stays on the entries it asked for."""
    rest = (lib.get("catalogue") or {}).get(section) or []
    if not rest:
        return
    out.append("")
    out.append(intro)
    for e in rest:
        why = (e.get("why") or "").strip()
        out.append(f"  {e['key']}" + (f" — {why}" if why else ""))


def render_index(lib=None):
    """The whole library as a LIST — every entry, what it is, and what its
    parameters MEAN sonically. No Csound.

    This is what the author reads before it has decided anything: enough to size
    up the tools ("does this library have something that rubs? something that
    beats? something hollow?") without the weight of every code block in the library.
    It costs about what the old word-matched excerpt cost (~6k tokens) and shows
    everything instead of eight entries a word comparison happened to hit.

    The parameter lines are the point, not decoration. `string` is not usable
    knowledge; `string` with `bow` running from "picked and let go: bright at the
    front, then darkening" to "drawn with a bow: standing, breathing, the top
    rubbed off" is — that is the difference between a name and a tool."""
    lib = lib if lib is not None else _load_library()
    out = ["## THE LIBRARY — what is on the shelf",
           "Every entry, what it is, and what its parameters do to the sound. The",
           "Csound itself is not here: name what you want and it will be opened."]

    out.append("")
    out.append("### Instruments")
    for it in lib["instruments"]:
        out.append(f"  {it['key']} — {it['why']}")
        for pname, spec in (it.get("params") or {}).items():
            rng = spec.get("range") or [0.0, 1.0]
            out.append(f"      {pname} ({rng[0]}..{rng[1]}): {spec.get('note', '')}")
            for aname, a in (spec.get("anchors") or {}).items():
                out.append(f"        {aname} — {a['gloss']}")

    out.append("")
    out.append("### Sound words (they belong IN the generation, not after it)")
    for adj in lib["adjectives"]:
        out.append(f"  {adj['key']} — {adj['why']}")

    out.append("")
    out.append("### Movements")
    for mot in lib["motions"]:
        tag = ", ".join(x for x in (
            f"moves the {mot['moves']}" if mot.get("moves") else "",
            mot.get("kind") or "",
            f"around {mot['rate_hz']} Hz" if mot.get("rate_hz") else "") if x)
        out.append(f"  {mot['key']}{f' ({tag})' if tag else ''} — {mot['why']}")
    return "\n".join(out)


def render_library(sel=None):
    """The library as the author reads it: instruments with their real Csound,
    their parameters with measured ranges and named anchors, the anchor value
    shown AS CODE where the generator could emit it, then the sound words and
    motions the prompt reached, with the lines each word is responsible for."""
    lib = sel if sel is not None else _load_library()
    out = []

    out.append("## INSTRUMENTS")
    out.append("Real Csound, as this build actually produces it. Each block reads")
    out.append("`kfreq` and writes one signal. Adapt, combine, depart from them.")
    for it in lib["instruments"]:
        if not has_code(it.get("code")):
            continue
        out.append("")
        out.append(f"### {it['key']} — {it['why']}")
        out.append(_indent(it["code"]))
        for pname, spec in (it.get("params") or {}).items():
            rng = spec.get("range") or [0.0, 1.0]
            out.append(f"  parameter `{pname}` {rng[0]}..{rng[1]}, default "
                       f"{spec.get('default')}: {spec.get('note', '')}")
            for aname, a in (spec.get("anchors") or {}).items():
                out.append(f"    {pname}={a['value']} — {aname}: {a['gloss']}")
        # The anchor code shows which LINE moves with a parameter. The full body is
        # already printed above, so quote only the lines that differ from it at each
        # anchor — the base plus five copies of the same twelve lines is exactly the
        # recital this file just stopped doing.
        #
        # A key is `axis=anchor`. It has to carry the axis, because an entry can
        # have exemplars for MORE THAN ONE of its parameters and this used to print
        # them all under `next(iter(params))` — the first parameter's name, whether
        # or not the variant belonged to it. `lco_param_audit.py` already read the
        # key this way; the two now agree.
        base_lines = set((it.get("code") or "").splitlines())
        deltas = {}
        for label, code in (it.get("anchor_code") or {}).items():
            axis, _, anchor = label.partition("=")
            changed = [l for l in code.splitlines() if l not in base_lines]
            # An anchor whose value IS the parameter's default has no delta from the
            # quoted body, and dropping it made the anchor vanish from the prompt
            # with nothing to say why — `sax`'s `growl=edge` sat at 0.15, the
            # default, so the author saw clean/growl/roar and no `edge`. Say instead
            # that the quoted code already is that anchor.
            deltas.setdefault(axis.strip(), []).append((anchor.strip() or axis,
                                                        changed))
        for axis, rows in deltas.items():
            out.append(f"  # how the code changes across `{axis}`:")
            for anchor, changed in rows:
                if not changed:
                    out.append(f"    # {anchor} — the code above already is this one")
                    continue
                out.append(f"    # {anchor}")
                for l in changed:
                    out.append(f"    {l.strip()}")

    _catalogue(out, lib, "instruments",
               "Also in the library, not quoted here. If one of these is what the "
               "prompt asks for, write it yourself in the same spirit:")

    out.append("")
    out.append("## SOUND WORDS (they belong IN the generation, not after it)")
    out.append("What each word means in code. Fold it into how the tone is MADE —")
    out.append("a word is a property of the generator, not an effect bolted on the end.")
    for adj in lib["adjectives"]:
        if not adj.get("code", "").strip():
            continue
        out.append("")
        out.append(f"### {adj['key']} — {adj['why']}")
        out.append(_indent(adj["code"]))

    _catalogue(out, lib, "adjectives",
               "Other words the library knows, without their code:")

    out.append("")
    out.append("## MOTION (movement is code: a free-running oscillator driving a parameter)")
    for mot in lib["motions"]:
        # The heading carries the KIND and the rate. The kind is the whole point of
        # the taxonomy -- does the movement return, is it regular, is it a movement
        # at all -- and the author is its only reader, so leaving it in the data
        # file would make the distinction invisible exactly where it must land.
        # The rate goes here too, not after the prose: a `why` ends in a full stop,
        # and appending ", around 0.19 Hz" to it reads as a typo.
        tag = ", ".join(x for x in (f"moves the {mot['moves']}" if mot.get("moves") else "",
                                    mot.get("kind") or "",
                                    f"around {mot['rate_hz']} Hz" if mot.get("rate_hz") else "")
                        if x)
        out.append("")
        out.append(f"### {mot['key']}{f' ({tag})' if tag else ''} — {mot['why']}")
        if mot.get("code", "").strip():
            out.append(_indent(mot["code"]))
        alt = mot.get("alt")
        if alt and (alt.get("code") or "").strip():
            out.append(f"  or, when {alt['when']}:")
            out.append(_indent(alt["code"]))

    _catalogue(out, lib, "motions", "Other movements the library knows:")
    return "\n".join(out)



# ─────────────────────────────────────────────────────────────────────────────
# The system prompt — library as orientation, host contract, platform invariants
# ─────────────────────────────────────────────────────────────────────────────
# The invariants are docs/LCO_CONCEPT.md §4. They are user-observable
# fundamentals: the oscillator is a SPECTRUM SOURCE, colour may travel but
# loudness may not, pitch belongs to the synth, and every sound MOVES unless the
# prompt asks for stillness.

_SYSTEM_HEAD = r"""You WRITE Csound orchestra code (Csound 6.18) for a synthesizer's oscillator. You are given a LIBRARY of real, working Csound idioms with measured parameter ranges and plain-language anchors. ADAPT and COMBINE them into the code that generates the sound the user describes. The library orients you; it is not a menu and you are not restricted to it.

WHAT YOU WRITE
Only the oscillator body: the lines that produce the raw signal. The host provides everything around it.

HARD RULES
- Read the pitch from `kfreq` (Hz, k-rate). It GLIDES. Three different things in a body carry a frequency and only the first is the pitch, so decide which one you are writing before you type a number:
  (a) PITCH is `kfreq` times a ratio — never a number. A body that invents its own register is unusable however good it sounds.
  (b) A RESONANCE may be FIXED in Hz, because a formant, a body resonance, a noise band or an LFO rate belongs to the BODY and not to the note — a real bell's formant does not move when you play a different key. Write the number and MARK it, the way the library's own bodies do: `abl0 reson abz0, 1200, 900, 1 ; bell formant, FIXED in Hz`. A body whose resonances are fixed sounds right over part of the range and wrong outside it (`fmvoice` needs roughly 880 Hz and up), which is a property to state, not a defect to correct.
  (c) A LANDMARK in the spectrum — "above the 6th harmonic", "just under the fundamental", "the top of the spectrum" — is a RATIO to `kfreq`, never Hz: 2200 Hz is the 40th harmonic of a 55 Hz note and the 2nd of an 880 Hz one, so as a fixed number it is a different word at every pitch. Clamp a high ratio to the band (`min(kfreq * koct1 * 8, sr * 0.45, 20000)`) so it does not leave it.
- Write your final audio into a variable named exactly `asig`.
- Define every variable before you use it, top to bottom. Give your variables distinct names; do not reuse a name for two things.
- Use only real Csound 6.18 opcodes. `vco2`'s imode is an INTEGER: 0 saw (every harmonic, 1/n), 2 pulse/square (odd harmonics, 1/n), 4 triangle/saw (odd harmonics, 1/n², much darker). Both 2 and 4 take `kpw` as their fourth argument and it is the SAME quantity in both — the fraction of the period spent in the first phase, 0.01 to 0.99: on imode 2 the duty (0.5 a square, away from it a pulse), on imode 4 where the ramp breaks (0.5 a triangle, toward either end a sawtooth). The pulse is the derivative of the ramp, so both spectra carry |sin(pi*n*kpw)| and differ by one power of n: same zeros, `kpw` and 1-`kpw` the same spectrum on either, odd harmonics alone at 0.5 on either. Measured, not guessed: imode 10 is NOT triangle, it is another pulse. There is no `vco1`.
- An opcode call has NO equals sign: write `asig poscil 0.6, kfreq` — never `asig = poscil 0.6, kfreq`. `=` is only for arithmetic (`kx = 0.5 + klfo`).
- An opcode STATEMENT names its RESULT VARIABLE first, then the opcode: `ahi atone asig, 2200`. Two consequences you must never break: (a) an opcode that returns audio must have that result variable — `atone asig, 2200` on its own, with nothing on its left, does not compile; (b) the opcode NAME is not a value — never write `aprea = atone`, and never pass a bare `atone`/`rand`/`oscili` as another opcode's argument (`mode rand 0.06, kfreq, kQ` is wrong). To use an opcode's result in an expression, give it its own line first (`ahi atone asig, 2200` then `asig = asig + ahi * 0.3`), or use the functional form WITH parentheses around all arguments (`asig = asig * (1 + oscili(0.18, 5.5, giSine))`).
- `mode` is a resonant FILTER, not an oscillator: `ares mode aexc, kfreq, kQ`. Its first argument is an audio EXCITATION you must define on its OWN line first — `aexc rand 0.06, 0.5, 1` — never a bare opcode inlined (`mode rand 0.06, kfreq, kQ` is wrong). Build a bell/metal/drum bank by driving several `mode` lines from that SAME `aexc`, exactly as the struck_bar, drum_head and cymbal idioms do.
- The physical models (`wgbow`, `wgclar`, `wgflute`, `wgbrass`, `wgbowedbar`, `wgpluck`, `barmodel`, `prepiano`, `platerev`) are DRIVEN bodies: they stand as long as they are driven, which is exactly what this oscillator needs, and their movement belongs in the driving parameter — bow pressure, jet ratio, lip tension, bow position, excitation colour. Their built-in vibrato argument (`kvamp`) stays 0 unless the user asked for vibrato by name: a wobble laid on the pitch is not the body changing, and it reads as a cheap preset. The same holds for the `fm*` family. Three measured facts you cannot see from the argument list. Every number here is measured at the rate the plugin COMPILES Csound at — 176400, host 44100 x 4 — and read after decimation to 44100, which is what the ear is given. A bare-44100 reading of this model is a different instrument and its numbers do not carry: measured, the same body's spectral centroid is 340 Hz at 44100 and 1235 Hz at 176400. (1) `wgclar`'s `kstiff` is documented as reed stiffness and is INERT in this build — output bit-identical from -0.9 to 0.0, checksum unchanged at both rates — so never put a control on it. (2) `kngain` IS the breath, and inside its documented range: over 0 to 0.5 the energy above 2 kHz goes 3.0% -> 26.3% and the spectral centroid 458 -> 1667 Hz while the rms only falls 0.429 -> 0.344, so it colours far more than it levels. The step sits between 0.20 and 0.30 and nothing moves below 0.20. Past 0.5 the model leaves self-oscillation (rms 0.062 at 0.7), so 0.5 is the ceiling — and an air or breath control on this bore belongs HERE, on nothing else. (3) `kamp` is the BLOWING PRESSURE and not an output level, but it is a GENTLE axis and will not carry a knob on its own: over 0.55 to 0.90 the 3rd partial moves only -8.6 -> -6.0 dB against the fundamental while the 5th travels the OTHER way, -10.5 -> -21.4 dB, and the rms rises smoothly 0.230 -> 0.424. There is no threshold, no speaking point and no blow-out anywhere in that range, so never write an axis whose anchors promise one. Put exactly ONE `wgclar` in a body: a second instance changes the first — measured, the 3rd partial of a bore at `kamp` 0.80 falls from -5.9 to -14.1 dB with an unused second bore standing beside it. And `wgbrass` produced NO output at all here — silent at 110, 220, 330, 440, 660 and 880 Hz with lip tension 0.5 at the plugin's rate — so do not reach for it.
- `gbuzz` IS the additive oscillator: `ares gbuzz kamp, kcps, knh, klh, kmul, giCos` — `knh` is how MANY harmonics, `kmul` how fast they fall away (0 = fundamental only, 0.95 = a buzzing reed). Both are k-rate, so both may move over the note. But `gbuzz` normalises to PEAK, not loudness: raising `knh` or `kmul` makes the tone BRIGHTER AND QUIETER — up to 6 dB, which reads as the wrong thing entirely. Hold the level with the exact stack sum, once, and then set `knh`/`kmul` freely. These two lines, exactly — the second is an opcode STATEMENT, so the result variable comes first and there is NO `=`, and the amplitude expression is simply its first argument:
    knrm    = ((1-kmul^knh)/(1-kmul)) / sqrt((1-kmul^(2*knh))/(1-kmul*kmul)*0.5)
    ares    gbuzz 0.17 * knrm, kfreq * koct1, knh, 1, kmul, giCos
  Writing `ares = gbuzz (0.17 * knrm) (...)` does not compile: `gbuzz` is an opcode, not a function you assign, and Csound answers with a bracket complaint that hides the real cause. Measured over the whole range (1..24 harmonics, kmul 0.2..0.95, centroid 220..2241 Hz): 0.00 dB. Keep `kmul` below 1 — at 1 the expression divides by zero.
- You shape SPECTRUM and TIMBRE only. Do NOT write an amplitude envelope on the output (no linen, adsr, madsr, expon on the way to `asig`) — loudness belongs to the player's envelope. The COLOUR may travel over the note; the LOUDNESS may not. A tone that fades out on its own is wrong. There is exactly ONE exception, and only when the user asks for it by name: `tremolo` is a word for a loudness pulsation, so it pulses — regularly, shallowly, and never fading. When a colour movement would drag the level with it (a waveshaper, a filter sweep, a partial fading in), do not chase the level with a follower — build the bright version ONCE, match its level to the clean one ONCE, and then CROSSFADE between them: `adrv = tanh(asig * 4.4)`, `adrv balance adrv, asig, 1`, `asig = asig * (1 - kpos) + adrv * kpos` with `kpos` in 0..1. Every motion example below is built that way and holds the loudness inside 0.05 dB at every pitch, because nothing has to track the movement. Balancing the MOVING signal instead makes the follower run inside the waveform period on bass notes and cancel the very harmonics the drive just made.
- ATTACK, for you, is SPECTRAL and not amplitudinal: the time the spectral components need to settle into nearly periodic oscillation. You do not own the loudness attack, so when the prompt says sharp, soft, hard, percussive or slow onset, that is about how fast your SPECTRUM arrives and settles — an upper band that lands instantly or fades in over 40 ms, a filter that opens fast or slowly, an FM index at full value from the first sample or reaching it late, a noise burst that gives way to the tone. Never a level ramp: the player's envelope already has one, and yours would fight it.
- Keep `asig` near +-0.5 peak. The host applies its own headroom and voice gain.
- The sound MOVES by default: a sweep, a beat, a shimmer, a morph. Only write a standing tone if the user explicitly asks for something static or still.
- A LOOP is a free-running `oscili`/`phasor`/`lfo` that NEVER resets, driving a parameter or a crossfade. If the user asks for a loop or for something repeating, write a REPEATING trajectory — never a one-shot `linseg`, which moves once and then holds.
- "a > b" (equivalently "a into b", "a morphing into b", "a turning into b", "a transition from a to b", "a becomes b") is ONE voice that STARTS as a and BECOMES b across the note — a true crossfade, NOT two things. Build it in exactly this shape, and give a and b their OWN variables — never write your final `asig` more than once:
    <a's OWN lines>                        ; a, built in full — as many lines as it takes
    asiga   = <a's output> * kvol1         ; the first timbre, in its own variable and on its own mix knob
    <b's OWN lines>                        ; b, built in full — as many lines as it takes
    asigb   = <b's output> * kvol2         ; the second timbre, in its own variable and on its own mix knob
    kmorph  = min(knote / 2.0, 1)          ; 0 -> 1 over 2 s then holds (knote is in scope, seconds since the note began)
    asig    = asiga * (1 - kmorph) + asigb * kmorph
  The `2.0` is NOT fixed — T is yours, and a SHORT T is how you write a transient. "a short glassy strike, then a pwm square" is `kmorph = min(knote / 0.08, 1)`: a is gone in 80 ms and b stands for the rest of the note. Do not reach for an amplitude envelope to make an end short. The crossfade already holds the loudness — a's energy is replaced by b's, not faded out — an envelope would take the loudness away from the player, and there is no per-end envelope for you to write one into: one note, one envelope, and it is the player's.
  Three ways this silently becomes "no transition at all" — each is WRONG for "a > b", never do them:
    (1) writing `asig` twice (`asig = <a>` … later `asig = <b>`): the second assignment ERASES the first, so only b is heard and everything above it is dead code. This is the most common mistake — a and b MUST meet in one crossfade line, not overwrite each other.
    (2) a static layer (`asig = <a> * kvol1 + <b> * kvol2`): that is a and b at once, forever — a LAYER, not a transition.
    (3) a bad `linseg` for the position (`linseg 0, 1, knote` passes a k-variable where linseg needs i-time CONSTANTS). Prefer `kmorph = min(knote / T, 1)`; if you must use linseg every argument is a constant — `kmorph linseg 0, 2, 1`.
  AN END OF A MORPH IS A WHOLE INSTRUMENT, NOT A ONE-LINER. Each end keeps every line it needs — including its own moving controls AND every library parameter line it came with, which is what the player turns while that end is sounding. That an end feeds a crossfade takes nothing away from it: a saxophone used as one end is still blown. NEVER freeze a k-rate control to a constant to make an end fit on one line: that silently deletes the very thing the user named. If the user asks for "sine > pulse width modulation" (or "sine > pwm"), b IS pulse-width MODULATION — its duty must go on sweeping after the morph arrives, so b keeps its LFO (`klfo oscili 0.5, 0.5`, `kpw = 0.5 + 0.6 * klfo`, `apw vco2 0.6, kfreq * koct1, 2, kpw`) and you write `asigb = apw - 0.6 * (2 * kpw - 1)`. Writing `vco2 …, 2, 0.5` there is a STATIC pulse wave — a different instrument from the one that was asked for, and the DC-correction line then reads `- 0.6 * (2 * 0.5 - 1)`, which is zero: dead code that proves the modulation was dropped. The same holds for every moving instrument used as an end — a bowed string still breathes, an organ still drifts, a filter sweep still sweeps.
  A REPEATING morph (a loop of a>b) drives kmorph from a free-running `oscili` instead of `min(knote…)`, so it sweeps back and forth forever.
- "a + b" means two layers sounding at once — the static mix of (2), correct ONLY when the user asked to layer, never as a substitute for a transition. You may layer up to THREE oscillators this way.
- "a through b" (equivalently "a driven by b", "a modulated by b", "b opening a", "a ring modulated by b", "a shaped by b") is the THIRD relation and it is neither of the two above: one sound ACTS ON the other instead of sounding beside it. Build both in full with their own variables and their own parameter lines, exactly as in a transition — being the argument of another instrument is not a demotion either — but b is not ADDED to a, it goes IN as an ARGUMENT of a. The coupled pair is ONE voice and shares `kfreq * koct1`, and each side is on its own mix knob.
    <a's OWN lines>                        ; a, built in full
    asiga   = <a's output> * kvol1
    <b's OWN lines>                        ; b, built in full
    asigb   = <b's output> * kvol2
    asig    = asiga * asigb                ; ring modulation: sum and difference only, no carrier
  or b opening a's filter — `zdf_ladder` takes its cutoff at AUDIO rate, so b can drive it directly:
    acut    = 200 + 4000 * abs(asigb)
    asig    zdf_ladder asiga, acut, 4
  Before you drive an argument, check its RATE in the opcode's signature: `foscili`'s FM index is k-rate, so an audio signal cannot BE an index there — only its ratios are `x`. An `a` where the opcode wants `k` does not compile, and the message names the opcode rather than the rate.
- EVERY PART YOU BUILD GETS ITS OWN `kvolN`, whatever the relation joins them. Part 1 is scaled by `kvol1`, part 2 by `kvol2`, part 3 by `kvol3` — the two ends of an "a > b" transition and the two sides of an "a through b" are parts in exactly this sense, and each of them is the player's to mix. A part that ignores its `kvolN` cannot be mixed and takes the fader off the panel. With one part, use `kvol1`. Pitch is the other way round: layers of an "a + b" take `kfreq * koct1` / `koct2` / `koct3`, while a transition and a coupled pair share `kfreq * koct1` — those ARE one voice, and only the mixing is per part.

AVAILABLE IN SCOPE
  kfreq  k-rate pitch in Hz (already glide-smoothed and limited)
  kvel   note velocity 0..1        kpres  pressure/aftertouch 0..1
  ktimb  timbre controller 0..1    knote  seconds since this note started
  ivoice this voice's number, 1..16 — DO NOT define it yourself, the host routes
         the output with it. Use it to give each voice its own phase or seed so a
         chord does not move in lockstep: `ivph = frac(ivoice * 0.6180339887)`.
  kvol1 kvol2 kvol3                per-PART mix (player knobs) — one per part you
         build, including each end of a transition and each side of a coupled pair
  koct1 koct2 koct3                per-layer octave multiplier (player knobs)
  (the player's sliders are not variables you write — see THE KNOBS THE PLAYER
   GETS below: they are the library's own parameter lines, kept in your body)
  giSine (sine table)  giCos (cosine table, for gbuzz/buzz)
  giCheb (Chebyshev transfer table)  giImp (short strike impulse table)
  sr kr ksmps                      Csound's own globals, usable in an expression —
         `min(sr * 0.45, 20000)` is how the library keeps a rising landmark inside
         the band. Cap it at 20000 as well as at the rate: the plugin may run Csound
         at 4x, where `sr * 0.45` is 79 kHz and stops bounding anything, and a body
         must not sound brighter because of a Settings switch

HOW TO ANSWER — you answer TWICE, and the first answer is not code.

FIRST TURN: THINK, in plain language, and write that thinking down — a short paragraph, not an essay:
  - What IS this sound? Which instrument, mechanism or physical body comes closest?
  - The words are a DESCRIPTION of a sound, not lookup keys. When the prompt names no instrument at all — "a dark growl", "rusty machinery", "like wet glass", "an angry insect" — this is where you work out what it would BE: what excites it, what resonates, what makes it dark or rough or restless. The library has no entry for most of what a player will ask for; you are expected to reason your way there from what the words describe, using the idioms as material.
  - What MOVES in it, and how fast?
  - Which library entries do you want OPENED? You are shown the shelf below — what each entry is and what its parameters do — but not the Csound. Name the entries you want to see (instruments, sound words, movements), and their code will be handed to you in the next turn. Name what you actually intend to use or look at; naming everything is as useless as naming nothing. If nothing on the shelf fits, say so and the whole library will be opened.
Write NO code in this first turn. No fence, no Csound lines. The shelf is a list of names, and you are choosing from it in your own words.

SECOND TURN: the entries you named arrive, quoted in full. NOW write the orchestra body, in exactly ONE fenced block:

```csound
<your Csound lines, with the library's parameter lines kept as they stand:>
kbowl   = 0.50   ; bowl[0.0..1.0]: which measured bowl the mode series is
kring   = 0.60   ; ring[0.0..1.0]: how long the shell holds
<the rest of the body>
asig    = abowl * kvol1
READING: <a short plain-language description of what you built, 5-12 words>
```

Inside the fence goes ONLY the oscillator body and that final READING line: no <CsoundSynthesizer>, no <CsInstruments>, no header (sr/ksmps/nchnls/0dbfs), no `instr`/`endin`, no `ftgen`, no score, no `out`/`outs`/`outch`. The host supplies all of it. Everything OUTSIDE the fence is your thinking and is discarded — so the fence must be there, and there must be exactly one.

THE KNOBS THE PLAYER GETS — you do not invent them, you KEEP them
The library declares what is playable about each of its bodies, and you can see it: a line that is at the same time the value your code uses and the name, range and gloss a player reads.

    kbowl   = 0.50   ; bowl[0.0..1.0]: which measured bowl the mode series is

EVERY SUCH LINE YOU KEEP IN YOUR BODY BECOMES A SLIDER under the player's hands. The host connects it to the slider itself — you never write `kp` anything, you never declare anything after READING. Write the line and it is wired.

- KEEP THE LINE WHOLE: the variable, a plain NUMBER, and the comment `; name[lo..hi]: what it does`, exactly as the library wrote it. Delete the comment and the sound is unchanged but the player loses the knob. Replace the number with an expression and the same is true — a knob is a number somebody can turn.
- THE BRACKET IS NOT YOURS. `[lo..hi]` is the travel the player's slider is wired to, and it is the library's measurement of what that axis can take. Widen it, narrow it, or write a different one and the line is no longer that parameter: it stays in your code and works exactly as you wrote it, but it gives no knob.
- KEEP IT WHERE THE LIBRARY PUT IT: at the TOP, ABOVE every line that reads the variable. Csound runs your body from the first line to the last, and a variable used before the line that sets it does not compile — `Variable 'kwidth' used before defined`. Collecting these lines at the end of the body, as if they were a declaration block, is the one way to lose a whole orchestra to this.
- THE NUMBER IS YOURS, and it is the only part that is. It is where the knob STARTS, so write the value this sound wants; the player hears that first and moves away from it. Use the range in the brackets and stay inside it.
- KEEP EVERY PARAMETER LINE OF EVERY PART YOU BUILD, and build every part in full so that those lines have something to act on. A part does not become less of an instrument because it is layered under another, crossfaded into, or used as an argument: the player gets its controls whatever the relation joins them, and dropping them is not editing, it is handing over an instrument that cannot be played. If a parameter needs a second generator or its own moving lines to mean anything — `analog_osc`'s `wave` crosses between a ramp and a pulse, its `age` is three drift lines — then you write those too, or you have not built that part. Measured on "a vibraphone > a saw wave": the saw end came out as one `vco2` with `kwave0 = 0.00` standing above it, read by nothing, and the player was handed a saw with one slider where the entry has five.
- The player sees COLUMNS, one per library entry you took a line from, in the order they appear in your body. At most three columns of four knobs. What is past that limit the host drops in the library's own order — that ceiling is the host's and is not yours to anticipate by leaving lines out.
- A LINE YOU KEEP MUST CHANGE THE SOUND. Keeping it is a promise to the player that this control does what the library says it does, so the variable has to reach the synthesis and move it. Two ways of breaking that promise have shipped: keeping `kstrings` and then never mentioning it again, and writing `aout = a * kwave + a * (1 - kwave)`, which is `a` at every setting — a crossfade between one signal and itself, written for a second generator that was never built. If you have no use for the parameter, fold it into your code as a plain number with no comment; a knob that cannot be felt is worse than one that is not there.
- INVENTING ONE GIVES THE PLAYER NOTHING. A line whose name the library does not declare for that body is not a knob — the names, the ranges and the words under them are the library's.
- Do not go looking for a knob for level, octave, pitch, attack, decay or filter cutoff. The synth already has those.

You have already reasoned about the sound in the first turn. Do not reason it out again in the second: choose, and write.
"""


_PARAMS_HEAD = """
THE SYNTH'S OWN CONTROLS — write what this sound needs, the player decides when it lands
Your oscillator sits inside a real instrument: a filter, five envelopes, three
LFOs, three slow drift LFOs, aftertouch amounts, noise, an amplifier chain
(distortion, chorus, phaser, tremolo) and two effects (delay, reverb). For this
sound you may set them. Use them for what belongs OUT THERE rather than inside
your body — a filter the words ask for, an envelope that opens something, an LFO
that moves it. What you build in Csound is still the spectrum; these are the
instrument around it.

Whether your settings actually move anything is not your decision and not your
worry: a switch called KNOBS puts them on the player's patch, and while it is
off they are kept and wait for it. So write them either way — describe the whole
sound, not the part that happens to be permitted at this moment.

This ADDS one thing to the fence rule above: besides the oscillator body and
the READING line, the fence may now also carry SET lines. Nothing else changes.
Write one line per setting, after READING:
  SET: <id> = <value>
A BARE number for a range - no unit, no comma, no second number - or one of the
listed words for a choice. Anything else is refused rather than guessed at. A
`;` comment after the value is fine. Nothing else changes in how you answer;
write no SET line at all if the sound does not need one.

Go carefully — this is the player's patch, not yours:
- An envelope or LFO target that already carries something is THEIRS. Prefer the
  ones that read `---`, and say what you take.
- Take as little as the sound needs. A sound that is finished in Csound needs
  nothing here.

HOW A MODULATION REACHES ITS TARGET — read this before you route anything.
A source does not SET its target. The target's own knob holds the POSITION; the
source MOVES it away from there, and Amount is how far it travels, measured in
the target's own unit:
  Filter (cutoff)   Amount 1 = 10 octaves    Pitch   Amount 1 = 12 semitones
  everything else   Amount 1 = the target's whole range
The filter's travel is not linear in the Amount: it is Amount^2.3 of those ten
octaves, so 0.25 = 0.4 oct, 0.5 = 2 oct, 0.67 = 4 oct, 1.0 = the whole audible
range. Full Amount from a low cutoff pins the filter open — for a sweep with a
top to it, ask for the octaves you want and read the position off that list.
Which way it moves is not yours to choose — it follows the source:
- An ENVELOPE only ever moves its target UP from the knob. Its Amount is 0..1
  and its level is 0..1, so the product can never be negative.
- An LFO and a drift LFO swing BOTH WAYS around the knob.
So an envelope sweep is written by MOVING THE KNOB FIRST, to where the sweep is
to begin, and letting the envelope travel from there. The commonest way to write
a filter sweep that cannot be heard is to route an envelope at Filter and leave
`filter_cutoff` where it stands at 20000: that is the top of its range, the
envelope pushes into a ceiling, and nothing moves. A sweep that opens starts
low — set `filter_cutoff` to a few hundred Hz and let the envelope open it.
A sweep that closes is an envelope with a HIGH cutoff and a falling shape (short
decay, sustain 0), or an LFO, which goes down as readily as up.

Units, since the ranges below carry none: every time is in MILLISECONDS, every
frequency and rate in HERTZ, filter drive in DECIBELS, and everything else is a
plain fraction of its own range.

Below: id, what it is, its range or its words, and where it stands right now.
"""


def render_params(params):
    """The shelf of synth knobs, one line each, exactly as it was handed over.

    Nothing is filtered here and nothing is ranked: the host decides what is on
    the shelf, this only lays it out. A choice parameter shows its words; a
    continuous one its measured range."""
    if not params:
        return ""
    out = [_PARAMS_HEAD]
    for e in params:
        pid = str(e.get("id", "")).strip()
        if not pid:
            continue
        name = str(e.get("name", "")).strip()
        if "choices" in e and e["choices"]:
            span = "[" + " | ".join(str(c) for c in e["choices"]) + "]"
        else:
            span = f"{float(e.get('min', 0)):g} .. {float(e.get('max', 0)):g}"
        now = e.get("value", "")
        if isinstance(now, (int, float)) and not isinstance(now, bool):
            now = f"{float(now):g}"
        # A continuous control may name points on its range (the envelope curves
        # do: their five old words are five values on the bend). Shown as the
        # host wrote it, appended, so a number range that carries meaning does
        # not arrive here as a bare pair of bounds.
        scale = str(e.get("scale", "")).strip()
        line = f"  {pid:<28} {name:<26} {span}   now {now}"
        out.append(f"{line}   ({scale})" if scale else line)
    return "\n".join(out) + "\n"


# A bare number and nothing else. No trailing unit: swallowing one turns
# "1.5 s" into 1.5 ms on a millisecond control, which is in range and therefore
# invisible. Refusing it is the safe reading, and the shelf shows no units for
# the author to copy in the first place.
_NUMBER = re.compile(r"^([-+]?\d+(?:[.,]\d+)?(?:[eE][-+]?\d+)?)$")
# "off"/"on" written the other ways a model writes them.
_BOOLWORDS = {"on": "on", "true": "on", "1": "on", "yes": "on", "enabled": "on",
              "off": "off", "false": "off", "0": "off", "no": "off", "disabled": "off"}


def read_settings(raw, params):
    """The SET lines the author wrote, CHECKED against the shelf it was given.

    Checked, not curated: this decides nothing about what the author should have
    set. An id that was never on the shelf is dropped, a word that is not one of
    a choice's own words is dropped, and a number outside a parameter's measured
    range is clamped into it — each with a note, so the panel can say what was
    corrected instead of the value quietly differing from what was asked for."""
    if not params:
        return []
    shelf = {str(e.get("id", "")): e for e in params if e.get("id")}
    out, seen = [], set()
    for pid, val in _SET.findall(raw or ""):
        if pid in seen:
            continue                      # the author wrote it twice; the first stands
        seen.add(pid)
        # Everything from a semicolon on is a Csound comment — the one language
        # this author writes, and the prompt invites it to say what it takes.
        text = val.split(";", 1)[0].strip().strip('"\'')
        entry = shelf.get(pid)
        if entry is None:
            out.append({"id": pid, "name": pid, "value": text, "ok": False,
                        "note": "no such control on the synth — not set"})
            continue
        choices = entry.get("choices") or []
        if choices:
            probe = text.lower()
            if [str(c).lower() for c in choices] == ["off", "on"]:
                probe = _BOOLWORDS.get(probe, probe)
            hit = next((c for c in choices if str(c).lower() == probe), None)
            if hit is None:
                out.append({"id": pid, "name": entry.get("name", pid), "value": text,
                            "ok": False,
                            "note": "not one of this control's settings — not set"})
                continue
            out.append({"id": pid, "name": entry.get("name", pid), "value": hit,
                        "ok": True, "note": ""})
            continue
        # A continuous control may still NAME points on its range — the envelope
        # curves do, because their five old words became five values on the bend
        # and an author that writes "exp" means the shape, not a failure. Only
        # the words the host itself put on the entry are accepted, so this can
        # never invent a value the shelf did not offer.
        words = entry.get("scale_words") or {}
        if words:
            hit = next((v for k, v in words.items() if str(k).lower() == text.lower()), None)
            if hit is not None:
                out.append({"id": pid, "name": entry.get("name", pid),
                            "value": float(hit), "ok": True, "note": ""})
                continue
        # A bare number and nothing else. A unit, a range, two numbers, a word —
        # all refused rather than squeezed into a number: a guessed value is
        # worse than none, and an in-range guess is worse still because nothing
        # about it looks wrong.
        m = _NUMBER.match(text)
        if m is None:
            out.append({"id": pid, "name": entry.get("name", pid), "value": text,
                        "ok": False, "note": "not a number — not set"})
            continue
        digits = m.group(1)
        # "1,500" is 1500 to half the world and 1.5 to the other half. Refuse it
        # rather than pick: on a millisecond control the two readings are a
        # factor of a thousand apart and both land in range.
        if "," in digits and len(digits.split(",")[1].split("e")[0].split("E")[0]) == 3:
            out.append({"id": pid, "name": entry.get("name", pid), "value": text,
                        "ok": False,
                        "note": "comma could be a decimal point or a thousands "
                                "separator — write it without one"})
            continue
        num = float(digits.replace(",", "."))
        lo, hi = float(entry.get("min", num)), float(entry.get("max", num))
        note = ""
        if num < lo or num > hi:
            note = f"asked for {num:g}, clamped into {lo:g}..{hi:g}"
            num = max(lo, min(hi, num))
        out.append({"id": pid, "name": entry.get("name", pid), "value": num,
                    "ok": True, "note": note})
    return out


# The player's knobs for the written body: three parts, four places each.
# FIXED, not derived from what the author wrote: the orchestra head then looks
# the same for every sound, so an offline render plays exactly what the plugin
# plays, and the host can resolve twelve channel pointers once instead of after
# every authoring.
LRO_PARTS = 3
LRO_SLOTS = "abcd"
LRO_CHANNELS = tuple(f"{n}{s}" for n in range(1, LRO_PARTS + 1) for s in LRO_SLOTS)
# What a channel nothing reads sits at. Nothing hears it — a `kp` the wiring did
# not put into the body is an unused variable — but the head still writes it, so
# that the twelve `chnset` lines keep one shape whatever was authored.
LRO_DEFAULT = 0.5


def _shelf_params(sel=None):
    """Every parameter the library DECLARES, by name: what may become a knob.

    One record per (entry, parameter), in library order, carrying what the panel
    shows — the entry's display name for the column, the range the entry declares
    and the short gloss the entry's code line gives it. `note` and `anchors` are
    deliberately left behind: they are pages long, and the knob is a slider.

    The declared range is here to IDENTIFY the entry a line came from, not to
    wire it: what a knob is wired to is the bracket in the line itself (see
    `read_controls`). A name can belong to more than one entry (`ring` to four of
    them today), so the caller resolves the owner against what the body actually
    carries; this only lays out the shelf."""
    lib = sel if sel is not None else _load_library()
    shelf, order = {}, 0
    for section in ("instruments", "adjectives", "motions"):
        for entry in (lib.get(section) or ()):
            declared = entry.get("params") or {}
            if not declared:
                continue
            # The entry's own line for each parameter, for its SHORT description
            # — and, because the author is told to keep a kept line whole, for
            # RECOGNISING a line as this entry's. `params[name]["note"]` is the
            # measurement and runs to a paragraph; this is the same sentence
            # written for a reader. Eleven declared parameters across five
            # entries have no line at all, and stay unrecognisable this way.
            glosses = {m.group("name").strip(): m.group("gloss").strip()
                       for m in _param_lines(entry.get("code") or "")}
            names = set(declared)
            for name, spec in declared.items():
                rng = (spec or {}).get("range") or []
                if len(rng) != 2:
                    continue
                try:
                    lo, hi = float(rng[0]), float(rng[1])
                except (TypeError, ValueError):
                    continue
                if lo == hi:
                    continue
                order += 1
                shelf.setdefault(name, []).append(
                    {"key": entry["key"], "entry": entry.get("name") or entry["key"],
                     "param": name, "range": (lo, hi),
                     "gloss": glosses.get(name, ""), "siblings": names, "order": order})
    return shelf


def _knob_label(name):
    """A library parameter name as the player reads it: `ratio 2` -> `Ratio 2`.

    Only the first letter of each word, never `.title()`: that would rewrite
    `finetune` as `Finetune` (right) and any future `pwm` as `Pwm` (wrong)."""
    return " ".join(w[:1].upper() + w[1:] for w in str(name).split())


def _param_lines(code):
    """Every library parameter line in a body, in order, ignoring commented-out
    ones.

    THE ONE ENUMERATION both `read_controls` and `wire_controls` walk, so a knob's
    `line` ordinal means the same thing to both. If they counted differently the
    wiring would land on the wrong line, which is the one failure here that would
    be silent and audible at once.

    `/* … */` matters because a parameter line inside one is not code: it would
    otherwise give the player a slider over a body that never reads the variable
    — exactly the dead knob this whole construction exists to make impossible.
    Nothing in the library uses block comments today; this is what keeps that
    from being an assumption about the author."""
    text = code or ""
    blocks = [m.span() for m in re.finditer(r"/\*.*?\*/", text, re.S)]
    return [m for m in _LIBPARAM.finditer(text)
            if not any(a <= m.start() < b for a, b in blocks)]


def _code_lines(code):
    """A body's lines with every comment blanked — what the body actually RUNS.

    In THIS order, because a `;` comment is the outer one: a body that writes
    `; the split follows Table I /* see the entry` has no block comment in it at
    all, and blanking `/*…*/` first swallowed the real code that followed. A `;`
    inside a string is not a comment either. Line COUNT and line NUMBERS are
    preserved, so an index into this list is an index into the body."""
    def uncomment(line):
        q = False
        for i, ch in enumerate(line):
            if ch == '"':
                q = not q
            elif ch == ";" and not q:
                return line[:i]
        return line

    lines = [uncomment(l) for l in (code or "").split("\n")]
    return re.sub(r"/\*.*?\*/", lambda m: re.sub(r"[^\n]", " ", m.group(0)),
                  "\n".join(lines), flags=re.S).split("\n")


# `kwave0 = 0.00`, standing above a `vco2` that was written for one waveform and
# read by nothing. That line is not a leftover: it is the FINGERPRINT of a
# control the author froze to a constant, and it is the exact shape the contract
# forbids ("NEVER freeze a k-rate control to a constant"). Nothing looked for it,
# so a part could arrive stripped of the very axis the user named and the panel
# would report the stripping as "the author took nothing".
_FROZEN = re.compile(r"^\s*(k\w+)\s*=\s*[-+]?[0-9]*[.,]?[0-9]+\s*$")


def frozen_controls(body):
    """The `k` variables set to a bare number that nothing in the body reads.

    Dead code in every case, and one specific kind of it: a part that was
    reduced until one of its controls had nothing left to act on. A variable
    that is genuinely a constant of the synthesis is READ — by the line it
    feeds — so this cannot fire on one; a name that appears only in a comment
    does not count as read, which is the whole reason comments come off first.

    Names, in body order, and the caller decides what a name is worth: this is
    reported to the AUTHOR as something to repair, never used to withhold a
    sound that plays (see `build_csound_response`)."""
    bare = _code_lines(body)
    out = []
    for n, line in enumerate(bare):
        m = _FROZEN.match(line)
        if m is None:
            continue
        var = m.group(1)
        pat = re.compile(rf"\b{re.escape(var)}\b")
        if not any(pat.search(l) for i, l in enumerate(bare) if i != n):
            out.append(var)
    return out


def read_controls(body, skip=None):
    """The library parameters that survived into the body — the player's knobs.

    A knob is not something the author declares. It is a line of the library's
    own shape (`_LIBPARAM`) standing in the written body, and the author's only
    say in it is the NUMBER: where the knob starts. The name and the range must
    be a parameter the library declares, so the panel shows the library's
    vocabulary and can show nothing else; the words under it come from the line,
    which is where the library wrote them.

    EVERYTHING HERE IS A FUNCTION OF THE BODY ALONE. What the authoring turn
    opened is deliberately not consulted: it was, and that was a defect — the
    same body then yielded different knobs on different channels depending on
    which entries happened to be open, so recompiling an UNEDITED body (which has
    no selection to consult at all) moved the player's `bowl` position onto
    `detune`. Since the author can only copy a line out of an entry it was shown,
    reading against the whole library costs nothing and makes the two paths agree
    by construction.

    Refused, and reported rather than silently dropped:
      * a name the library does not declare. That is the author inventing a knob,
        and an invented one is exactly what this path exists to make impossible.
      * a line whose variable nothing in the body reads. Keeping the line buys
        the wiring, not a use for it, and a knob nothing reads is a slider under
        the player's hand that moves nothing.
      * a bracket that disagrees with the range the owning entry declares. The
        range is the library's, not the author's: a `pick [0.25..0.35]` line
        widened to `[0.0..1.0]` wires a slider that takes the instrument down
        45 dB at both ends, and no compile and no `perform_check` sees it. Whose
        range it was is then not decidable here, so it is not a knob.
      * a fourth column, or a fifth knob in a column: three parts of four is what
        the panel holds.
      * a line `skip` names. That is the RENDERED verdict coming back — see
        `dead_knobs`, which turns the wired orchestra at both ends of a knob and
        finds that not one sample of the sound moved. It is a second pass because
        it costs a render and this function costs nothing, and it comes back
        HERE rather than pruning the result so that the slot and column
        arithmetic stays in the one place that owns it: withdrawing the first
        knob of a column has to free its channel for the second, and a column
        whose every knob dies must not be left as a heading over nothing.
    A starting value outside that range is CLAMPED with a note, the same way
    `read_settings` treats one — the number is a position, the knob is the
    deliverable."""
    code = body or ""
    hits = _param_lines(code)
    skip = skip or {}

    # THE BODY MUST ACTUALLY READ THE VARIABLE. Keeping the line guarantees the
    # wiring, not that anything downstream looks at it, and an author that keeps
    # a line for its NAME and then writes its own synthesis around it leaves a
    # slider that moves nothing — the exact thing this construction claims to
    # make impossible. Measured on a shipped instrument (2026-08-01):
    # `kstringsD = 0 + 1 * kp2a ; strings [0..1]: …` was declared once and read
    # zero times, and the panel showed a Strings slider under the player's hand.
    #
    # A use that stands only in a comment does not count, so comments come off
    # first (`_code_lines`).
    bare = _code_lines(code)

    # `split("\n")`, not `splitlines()`, and the same split on both sides of this
    # index: `splitlines()` also breaks on \x0c, \x85, U+2028 and four more, so a
    # single stray control character above a declaration shifted every line
    # number, let the declaration match ITSELF, and passed every knob in the
    # body. A gate that fails open on one bad byte is not a gate, and the
    # author's text has arrived mis-decoded before now (`_repair_mojibake`).
    def is_read(var, decl_line):
        pat = re.compile(rf"\b{re.escape(var)}\b")
        return any(pat.search(l) for n, l in enumerate(bare) if n != decl_line)

    # WHICH PARTS THIS BODY MIXES, which is a different question from which
    # columns it has and must not be answered with the same number. A COLUMN is a
    # library entry a parameter line survived from; a PART is `kvol1`/`kvol2`/
    # `kvol3`, the scaffold's own mix variables, and the author is told to scale
    # every part it builds by its own `kvolN` — the two ends of an `a > b` and the
    # two sides of an `a through b` included, because a fader per part is the
    # player's, not something the relation may take away (BJ 2026-08-06:
    # "selbstverständlich gibt es zu jedem Partial einen mix-Regler"). The two
    # decompositions still cross: two parts can be built out of ONE entry, and an
    # entry can carry a line into a part without owning it. Answering "how many
    # columns" with "how many parts" put a level under a column heading that drove
    # a variable the body never read, and left a real part with no level at all.
    #
    # So this is read off the body directly. The names are the scaffold's, fixed
    # and known, which is exactly why this one is decidable where "which entry is
    # layer 2" is not.
    layers = [n for n in (1, 2, 3)
              if any(re.search(rf"\bkvol{n}\b", l) for l in bare)]

    if not hits:
        return {"parts": [], "params": [], "refused": [], "layers": layers}

    shelf = _shelf_params()
    present = {m.group("name").strip() for m in hits}
    # WHICH ENTRY a name belongs to, when several declare it — `pick` is both
    # `plucked_wire`'s and `string`'s, `ring` belongs to four. This decides the
    # COLUMN and its caption, and which declared range the line must match.
    #
    # WHAT THE LINE SAYS, first of all. The author is told to keep a kept line
    # WHOLE, so a sentence reproduced word for word is not a coincidence: it is
    # the entry the line was copied out of, and no amount of circumstantial
    # agreement outweighs it. Nothing else separates the three entries that each
    # write a `ring` line — "how long the metal takes" is not "how long the drive
    # holds" — and counting siblings first gets those wrong in both directions: a
    # body holding `metallic_fm`'s and `supersaw`'s real lines side by side has
    # three of `fm_bell`'s parameter NAMES in it, and hands both entries' knobs to
    # a bell that was never opened. Checked against the library: no two entries
    # say the same sentence for the same name, so this never ties. A reworded
    # comment simply falls through to the terms below.
    #
    # THEN COUNT: the entry whose other parameters this body also carries is the
    # one it was written from. Not the fraction of that entry's own parameters —
    # normalising by entry size hands `drive` to the two-parameter `driven_metal`
    # over the five-parameter `analog_osc` whose other axis is right there, and
    # splits one oscillator across two columns.
    #
    # THEN a matching bracket, which discriminates the three names whose entries
    # declare different ranges (`pick`, `stretch`, `age`); then the fraction; then
    # the library's own order.
    #
    # THE BRACKET MUST NOT OUTRANK THE COUNT, however tempting: the refusal below
    # compares the line's bracket against the range of whichever entry wins here,
    # so a vote that PREFERS the entry agreeing with the bracket can only ever
    # refuse a name no entry declares that way. Tried, and it made exactly the
    # three names the check exists for unrefusable: a `plucked_wire` body with
    # `pick` widened from 0.25..0.35 to 0..1 was handed to `string`, accepted, and
    # wired the pickup position over its whole travel.
    def owner_of(name, lo, hi, gloss):
        cands = shelf.get(name) or []
        if not cands:
            return None
        def score(r):
            hit = len(r["siblings"] & present)
            said = 1 if (r["gloss"] and r["gloss"] == gloss) else 0
            same = 1 if (abs(r["range"][0] - lo) < 1e-9
                         and abs(r["range"][1] - hi) < 1e-9) else 0
            return (said, hit, same,
                    hit / max(1, len(r["siblings"])), -r["order"])
        return max(cands, key=score)

    parts, params, refused, column = [], [], [], {}
    for index, m in enumerate(hits):
        name = m.group("name").strip()
        try:
            lo = float(m.group("lo").replace(",", "."))
            hi = float(m.group("hi").replace(",", "."))
        except ValueError:                                   # pragma: no cover
            refused.append(f"{name} — {m.group('lo')}..{m.group('hi')} is not a range")
            continue
        if lo == hi:
            refused.append(f"{name} — its range is a single point ({lo:g}), "
                           f"so there is nothing to turn")
            continue
        if not is_read(m.group("var"), code[:m.start()].count("\n")):
            refused.append(f"{name} — nothing in the body reads "
                           f"{m.group('var')}, so the slider would move nothing")
            continue
        if index in skip:
            refused.append(f"{name} — {skip[index]}")
            continue
        rec = owner_of(name, lo, hi, m.group("gloss").strip())
        if rec is None:
            refused.append(f"{m.group('var')} — `{name}` is not a library parameter; "
                           f"only what the library declares becomes a knob")
            continue
        # THE RANGE IS THE LIBRARY'S TOO, and this is where that is enforced. A
        # bracket the author changed is not a narrower knob, it is a knob whose
        # provenance is gone: widened to a rival entry's range it is silently the
        # wrong axis, and nothing downstream can see it — it compiles, it plays,
        # and it takes the instrument down 45 dB at both ends of its own slider.
        # So it is not a knob. The line still stands in the body exactly as
        # written and the sound is unchanged; only the slider is withheld.
        dlo, dhi = rec["range"]
        if abs(dlo - lo) > 1e-9 or abs(dhi - hi) > 1e-9:
            refused.append(f"{name} — the line reads {lo:g}..{hi:g} where "
                           f"{rec['entry']} declares {dlo:g}..{dhi:g}; the range "
                           f"is the library's, so this is no longer its parameter")
            continue
        if rec["key"] not in column:
            if len(parts) >= LRO_PARTS:
                refused.append(f"{name} — {rec['entry']} would be a "
                               f"{len(parts) + 1}th column; only {LRO_PARTS} fit")
                continue
            column[rec["key"]] = len(parts) + 1
            parts.append({"n": len(parts) + 1, "name": rec["entry"]})
        n = column[rec["key"]]
        taken = sum(1 for p in params if p["part"] == n)
        if taken >= len(LRO_SLOTS):
            refused.append(f"{name} — {rec['entry']} already has {len(LRO_SLOTS)} "
                           f"knobs, which is all a column holds")
            continue
        try:
            v = float(m.group("value").replace(",", "."))
        except ValueError:                                   # pragma: no cover
            refused.append(f"{name} — {m.group('value')!r} is not a number")
            continue
        pos, note = (v - lo) / (hi - lo), ""
        if pos < 0.0 or pos > 1.0:
            note = f"the body set {v:g}, outside {name}'s {lo:g}..{hi:g}"
            pos = max(0.0, min(1.0, pos))
        slot = LRO_SLOTS[taken]
        params.append({"ch": f"lroP{n}{slot}", "part": n, "slot": slot,
                       "name": _knob_label(name), "value": pos,
                       # The library's own short line on the parameter; the one in
                       # the body only if the entry has none (five entries declare
                       # parameters they never write a line for).
                       "gloss": rec["gloss"] or m.group("gloss").strip(),
                       "note": note,
                       # For `wire_controls`, which rewrites exactly these lines:
                       # `line` is the ordinal among `_param_lines`, and lo/hi the
                       # bracket the knob's 0..1 is mapped back onto.
                       "line": index, "lo": lo, "hi": hi})
    return {"parts": parts, "params": params, "refused": refused,
            "layers": layers}


def wire_controls(body, controls):
    """The body with each knob's number replaced by the knob.

    THE AUTHOR NEVER WIRES ANYTHING — this does, and that is the whole point of
    reading the knobs off the library instead of off a declaration: a model that
    writes a perfect contract and then leaves its own fixed numbers in the code
    (measured, and the reason this path was rebuilt) can no longer produce a
    slider that moves nothing.

        kbowl   = 0.50   ; bowl[0.0..1.0]: …   ->   kbowl   = 0 + 1 * kp1a   ; bowl[0.0..1.0]: …

    Only the number changes. The comment stays exactly as it was, so the wired
    orchestra still says what each line is, and ONE line stays one line —
    `_BODY_OFFSET` maps Csound's error lines back onto what the author wrote."""
    knobs = {k["line"]: k for k in (controls or {}).get("params", ())}
    text = body or ""
    if not knobs:
        return text
    # Back to front, so an earlier rewrite cannot move a later match's offsets.
    out = text
    for index, m in reversed(list(enumerate(_param_lines(text)))):
        k = knobs.get(index)
        if k is None:
            continue
        expr = f"{k['lo']:g} + {k['hi'] - k['lo']:g} * kp{k['part']}{k['slot']}"
        out = out[:m.start("value")] + expr + out[m.end("value"):]
    return out


def system_prompt(prompt="", sel=None, params=None):
    """The head plus the library INDEX — what is on the shelf, without the code.

    One system prompt for the whole conversation, and it never varies with the
    prompt: the author sees the entire library listed and decides for itself
    what it wants opened. `sel` is accepted for callers that already hold an
    opened selection and want the quoted pages inline instead (offline probes,
    the parity tools); the live path does not use it, because the pages arrive
    in their own turn once the author has asked for them."""
    shelf = render_params(params)
    if sel is not None:
        return _SYSTEM_HEAD + "\n" + shelf + "\n" + render_library(sel)
    return _SYSTEM_HEAD + "\n" + shelf + "\n" + render_index()



class CompilerUnavailable(Exception):
    """The environment cannot compile anything. NOT an authoring failure: it must
    never be shown to the model as a Csound diagnostic, and no retry can fix it."""


def _executable(path):
    return bool(path) and os.path.isfile(path) and os.access(path, os.X_OK)


def _csound_binary():
    """Absolute path to a usable Csound CLI, or None.

    T5YNTH_CSOUND is validated like any other candidate: a directory, a
    non-executable file or a leftover bare "csound" would otherwise be returned
    as a compiler, and the failure would surface six inferences later as the
    author's fault instead of the setting's."""
    explicit = os.environ.get("T5YNTH_CSOUND")
    if explicit:
        if _executable(explicit):
            return explicit
        resolved = shutil.which(explicit)
        if _executable(resolved):
            return resolved
        return None
    found = shutil.which("csound")
    if _executable(found):
        return found
    for cand in _CSOUND_CANDIDATES:
        if _executable(cand):
            return cand
    return None


def _bundled_csound_libs():
    """The Csound the HOST ships, if the backend runs from inside one.

    macOS: tools/bundle_csound_macos.sh flattens the framework to
    <App>.app/Contents/libs/CsoundLib64 and rewrites every load command to
    @loader_path/../libs.

    Windows: CMakeLists.txt:440 copies csound64.dll and its plugins64 beside the
    module that loads it — the .exe for the standalone, Contents/x86_64-win for
    the VST3 — and the backend sits in a directory under that. Nothing else here
    can find it: it is not on PATH, ctypes.util.find_library looks for
    "CsoundLib64.dll" under a different name, and every other candidate in this
    file is a POSIX path. Without this walk the whole module reports NO_COMPILER
    on Windows, which does not merely silence the gates — build_csound_response
    refuses to author at all before it spends an inference.

    THE SOURCE CHECKOUT IS THE THIRD CASE and it was missing, which made every
    gate and every measurement in `tools/` render against whatever `csound` sat
    on PATH, with no opcode directory set at all — a different vocabulary from
    the one that plays (BJ 2026-08-05: "wir arbeiten nicht mit der
    homebrew-installation"). `third_party/csound/<platform>/` holds the exact
    bytes the app ships, so a checkout can point at those and measure what it
    delivers. It comes LAST: an installed host's own copy always wins."""
    here = Path(getattr(sys, "_MEIPASS", "") or os.path.abspath(sys.argv[0]))
    ancestors = [here] + list(here.parents)
    for parent in ancestors:
        if parent.name == "Contents":
            yield str(parent / "libs" / "CsoundLib64")
            break
    for parent in ancestors:
        dll = parent / "csound64.dll"
        if dll.is_file():
            yield str(dll)
            break
    vendor = Path(__file__).resolve().parent.parent / "third_party" / "csound"
    for rel in ("macos-arm64/lib/CsoundLib64", "windows-x64/bin/csound64.dll"):
        cand = vendor / rel
        if cand.is_file():
            yield str(cand)


def _opcodedir_beside(lib_path):
    """The plugin-opcode directory shipped NEXT TO a Csound library, or None.

    Csound finds its plugin opcodes through a path baked in when the library was
    built, so a copy inside an app bundle keeps reaching for the build machine's
    tree — measured 2026-07-26: with the bundled modules 2267 opcode entries
    register, with none of them 1917, and the missing ones include scanu/scans,
    fractalnoise, tvconv, ftgenonce, limit1 and GEN padsynth.
    tools/bundle_csound_macos.sh therefore
    ships Opcodes64 beside the library, and both the engine (CsoundEngine.cpp) and
    this gate point Csound at it — the same directory for both, or the gate would
    judge an orchestra by a different vocabulary than the one that plays it.

    `plugins64` is the same directory under its Windows name: CMakeLists.txt:440
    copies it beside csound64.dll, and CsoundEngine.cpp:218 points Csound there
    from the module's own directory. Same rule, same reason."""
    if not lib_path or not os.path.isabs(lib_path):
        return None
    beside = os.path.dirname(lib_path)
    for name in ("Opcodes64", "plugins64"):
        cand = os.path.join(beside, name)
        if os.path.isdir(cand):
            return cand
    return None


def _rawwavedir_beside(lib_path):
    """STK's rawwave data directory shipped NEXT TO a Csound library, or None.

    Same sibling rule as the opcode directory, and for the same reason — but the
    mechanism is an ENVIRONMENT VARIABLE, because that is the only handle Csound's
    STK module offers. Measured 2026-08-06 against the vendored payload: with
    RAWWAVE_PATH unset the module refuses to register and says so ("STK opcodes not
    available: define environment variable RAWWAVE_PATH"), and 2267 opcode entries
    exist; with it set, 2294 — the 27 STK opcodes (STKBowed, STKBlowBotl,
    STKModalBar, STKSaxofony, …) that would otherwise not be there at all.

    The variable is only ever set to a directory that EXISTS and is complete.
    A rawwave file STK asks for and does not find is not a compile error and not
    silence: `stk::StkError` propagates out of the module as an uncaught C++
    exception and `abort()`s the process (measured, with the directory emptied).
    Inside a plugin that is the host DAW."""
    if not lib_path or not os.path.isabs(lib_path):
        return None
    cand = os.path.join(os.path.dirname(lib_path), "rawwaves")
    if os.path.isdir(cand):
        return cand
    return None


def _csound_opcodedir():
    """The bundled opcode dir the CLI must be pointed at, or None. Derived from
    the library the host handed us (T5YNTH_CSOUND_LIB) even when the check itself
    runs through the CLI: the CLI and the library must see one vocabulary."""
    for path in [os.environ.get("T5YNTH_CSOUND_LIB")] + list(_bundled_csound_libs()):
        found = _opcodedir_beside(path)
        if found:
            return found
    return None


def _csound_rawwavedir():
    """The bundled STK rawwave dir, or None. Same search order as the opcode dir."""
    for path in [os.environ.get("T5YNTH_CSOUND_LIB")] + list(_bundled_csound_libs()):
        found = _rawwavedir_beside(path)
        if found:
            return found
    return None


def _csound_child_env():
    """Environment for a Csound CLI child. OPCODE6DIR64 is set for the CHILD only
    — never in this process, where it would also redirect any other Csound that
    happens to be loaded here. RAWWAVE_PATH rides along for the same reason it is
    set at all: without it a child renders an orchestra with 27 fewer opcodes than
    the plugin has, which is the divergence between gate and engine this whole
    lookup exists to close."""
    env = dict(os.environ)
    opcodedir = _csound_opcodedir()
    if opcodedir:
        env["OPCODE6DIR64"] = opcodedir
    rawwaves = _csound_rawwavedir()
    if rawwaves:
        env["RAWWAVE_PATH"] = rawwaves + os.sep
    return env


def _csound_library():
    """A loaded CsoundLib64 handle with the entry points the gate needs, or None."""
    global _csound_lib_cache
    if _csound_lib_cache is not False:
        return _csound_lib_cache

    _csound_lib_cache = None
    explicit = os.environ.get("T5YNTH_CSOUND_LIB")
    found = ctypes.util.find_library("CsoundLib64") or ctypes.util.find_library("csound64")
    for cand in ([explicit] if explicit else []) + list(_bundled_csound_libs()) \
                + list(_CSOUND_LIB_CANDIDATES) + ([found] if found else []):
        try:
            lib = ctypes.CDLL(cand)
            lib.csoundCreate.restype = ctypes.c_void_p
            lib.csoundCreate.argtypes = [ctypes.c_void_p]
            lib.csoundSetOpcodedir.argtypes = [ctypes.c_char_p]
            lib.csoundCompileCsdText.restype = ctypes.c_int
            lib.csoundCompileCsdText.argtypes = [ctypes.c_void_p, ctypes.c_char_p]
            lib.csoundSetOption.argtypes = [ctypes.c_void_p, ctypes.c_char_p]
            lib.csoundCreateMessageBuffer.argtypes = [ctypes.c_void_p, ctypes.c_int]
            lib.csoundGetMessageCnt.argtypes = [ctypes.c_void_p]
            lib.csoundGetMessageCnt.restype = ctypes.c_int
            lib.csoundGetFirstMessage.argtypes = [ctypes.c_void_p]
            lib.csoundGetFirstMessage.restype = ctypes.c_char_p
            lib.csoundPopFirstMessage.argtypes = [ctypes.c_void_p]
            lib.csoundDestroyMessageBuffer.argtypes = [ctypes.c_void_p]
            lib.csoundDestroy.argtypes = [ctypes.c_void_p]
        except (OSError, AttributeError):
            continue
        # The performing half, in its own try: a library that compiles but is
        # missing one of these must still serve the syntax gate, which is all it
        # was ever asked for. Absence disables `render_child_main`, nothing else.
        try:
            lib.csoundStart.restype = ctypes.c_int
            lib.csoundStart.argtypes = [ctypes.c_void_p]
            lib.csoundPerformKsmps.restype = ctypes.c_int
            lib.csoundPerformKsmps.argtypes = [ctypes.c_void_p]
            lib.csoundCleanup.restype = ctypes.c_int
            lib.csoundCleanup.argtypes = [ctypes.c_void_p]
        except AttributeError:
            pass
        # csoundErrCnt is EXPORTED but not declared in csound.h (it lives on the
        # internal struct as GetErrorCnt, csoundCore.h:1402), so it is bound on
        # its own and never required: measured on 6.18, a body that compiles and
        # then dies at its first k-cycle leaves csoundCleanup returning 0 and
        # csoundPerform returning its ordinary end-of-score 2 — the public API
        # simply does not carry the perf error count out. Where the symbol is
        # missing, render_child_main reads Csound's own printed verdict instead.
        try:
            lib.csoundErrCnt.restype = ctypes.c_int
            lib.csoundErrCnt.argtypes = [ctypes.c_void_p]
        except AttributeError:
            pass
        # Before the first csoundCreate: the setting is global to this loaded
        # image and is read when an instance is created.
        opcodedir = _opcodedir_beside(cand)
        if opcodedir:
            lib.csoundSetOpcodedir(opcodedir.encode("utf-8"))
        # STK has no API for this — the module reads getenv("RAWWAVE_PATH") when
        # it loads, which is inside csoundCreate. So unlike the opcode directory
        # it has to go into THIS process's environment. That is narrower than it
        # looks: nothing else here reads the variable, and the alternative is a
        # syntax gate that rejects every STK opcode the engine can play.
        #
        # It overwrites an ambient value on purpose, exactly as CsoundEngine.cpp
        # does: a stale path from an old STK install does not make the module
        # decline, it makes the module register and then abort() the process on
        # the first file it cannot open. The shipped directory is the only one
        # this code can vouch for. Beside the loaded library first; the payload
        # otherwise, which is the case in a source checkout, where the library
        # that loads is the machine's and only the payload has the data.
        rawwaves = _rawwavedir_beside(cand) or _csound_rawwavedir()
        if rawwaves:
            os.environ["RAWWAVE_PATH"] = rawwaves + os.sep
        _csound_lib_cache = lib
        break
    return _csound_lib_cache


_csound_lib_cache = False   # False = not looked for yet; None = looked, absent


def _check_via_library(csd):
    """(ok, log) from CsoundLib64 in-process — the engine's own call sequence
    (CsoundEngine.cpp:374-388): create, -n -d, compile the CSD text, read the
    message queue. No csoundStart: nothing here is meant to make sound."""
    lib = _csound_library()
    if lib is None:
        raise CompilerUnavailable(NO_COMPILER)
    cs = lib.csoundCreate(None)
    if not cs:
        raise CompilerUnavailable(NO_COMPILER)
    try:
        lib.csoundCreateMessageBuffer(cs, 0)   # queue-only, not to our stderr
        lib.csoundSetOption(cs, b"-n")
        lib.csoundSetOption(cs, b"-d")
        # Quiet the per-note statistics. Csound still prints its score-teardown
        # summary straight to stderr from csoundDestroy (after the message
        # buffer is gone), so backend_stderr.log picks up a few hundred bytes
        # per check on this path — noise, not a failure.
        lib.csoundSetOption(cs, b"-m0")
        rc = lib.csoundCompileCsdText(cs, csd.encode("utf-8"))
        parts = []
        for _ in range(lib.csoundGetMessageCnt(cs)):
            msg = lib.csoundGetFirstMessage(cs)
            if msg:
                parts.append(msg.decode("utf-8", "replace"))
            lib.csoundPopFirstMessage(cs)
        return rc == 0, "".join(parts)
    finally:
        lib.csoundDestroyMessageBuffer(cs)
        lib.csoundDestroy(cs)


RENDER_FLAG = "--lro-render"    # public: pipe_inference.py dispatches on it
_RENDER_BAD_CALL = 2        # this module called the child wrongly
_RENDER_NO_COMPILER = 3     # the child found no compiler
# Neither is a statement about the orchestra, and no caller may read one as one.
_RENDER_ENV_FAULT = (_RENDER_BAD_CALL, _RENDER_NO_COMPILER)


def render_child_main(argv):
    """`csound(1)`, reduced to what these gates ask of it, on the BUNDLED library.

    Every check in this module that has to hear a body — the perform check and
    the knob gate — needs a real performance, and performing means csoundStart.
    Doing that in this process would run an authored orchestra inside the backend
    that holds a multi-GB model: an endless loop hangs the instrument, an abort
    takes the loaded model with it. So it goes in a child, as it always did.

    What changed is WHICH child. Until now it could only ever be an installed
    csound CLI, and there is none inside the app: tools/bundle_csound_macos.sh
    ships CsoundLib64 and its Opcodes64, not a command-line binary. On every
    machine without Homebrew Csound — which is every user machine the bundling
    exists for — both checks therefore returned "unchecked, fine", and a body
    that compiles but makes no sound went to the engine as a finished
    instrument. The engine plays such an install perfectly; nobody was ever
    checking what it played.

    This is that missing binary: the app re-runs ITSELF with `--lro-render`, and
    this function loads the library the engine loads and performs the CSD with
    it. Process boundary kept, no system install needed, one compiler.

    argv is Csound's own: options first, the CSD path last. They are passed
    through verbatim to csoundSetOption, which is the same parser the CLI uses,
    so both call sites keep the flags they already had.

    ONE DIFFERENCE, measured, and it is not removable from this side: where an
    option is given BOTH on the command line and in the CSD's own `<CsOptions>`,
    the CLI's command line wins and this child's loses — csoundSetOption runs
    before csoundCompileCsdText, and the CSD's block overrides it. Nothing here
    hits that today because `_knob_render` already rewrites the scaffold's
    `<CsOptions>` before it asks for a file, which it has to do for the CLI as
    well. A future caller that adds a flag the scaffold also names would find the
    two children disagreeing, so: strip it from the CSD, do not merely pass it.

    Returns a process exit code: 0 played, 1 Csound refused it, and
    `_RENDER_ENV_FAULT` for the codes that say nothing about the orchestra."""
    if not argv:
        print("lro-render: no CSD given", file=sys.stderr, flush=True)
        return _RENDER_BAD_CALL
    options, csd_path = argv[:-1], argv[-1]
    lib = _csound_library()
    if lib is None or not hasattr(lib, "csoundPerformKsmps"):
        print(f"lro-render: {NO_COMPILER}", file=sys.stderr, flush=True)
        return _RENDER_NO_COMPILER
    try:
        with open(csd_path, "r", encoding="utf-8", errors="replace") as fh:
            csd = fh.read()
    except OSError as exc:
        print(f"lro-render: {exc}", file=sys.stderr, flush=True)
        return _RENDER_BAD_CALL

    cs = lib.csoundCreate(None)
    if not cs:
        print(f"lro-render: {NO_COMPILER}", file=sys.stderr, flush=True)
        return _RENDER_NO_COMPILER
    drained = []
    try:
        lib.csoundCreateMessageBuffer(cs, 0)
        for opt in options:
            if lib.csoundSetOption(cs, opt.encode("utf-8")) != 0:
                # Not fatal — Csound goes on with the option ignored — but silence
                # here would make this child differ from the CLI without saying so.
                print(f"lro-render: Csound rejected the option {opt!r}",
                      file=sys.stderr, flush=True)

        def drain():
            for _ in range(lib.csoundGetMessageCnt(cs)):
                msg = lib.csoundGetFirstMessage(cs)
                if msg:
                    drained.append(msg.decode("utf-8", "replace"))
                lib.csoundPopFirstMessage(cs)

        rc = lib.csoundCompileCsdText(cs, csd.encode("utf-8"))
        if rc == 0:
            rc = lib.csoundStart(cs)
        if rc == 0:
            # The CLI's own loop: csoundPerformKsmps returns non-zero at the end
            # of the score.
            while lib.csoundPerformKsmps(cs) == 0:
                drain()
            rc = lib.csoundCleanup(cs)
            # AND THEN THE PART THE RETURN CODES DO NOT TELL. A body that
            # compiles and dies at its first k-cycle — `vco2 kamp, kcps, 1`,
            # imode bit 1 being "skip initialisation" — is exactly what this
            # check exists to catch, and after it csoundCleanup returns 0 and
            # csoundPerform returns its ordinary 2 while the CLI exits 1
            # (measured, 6.18). Csound counts the errors; only the count says so.
            counter = getattr(lib, "csoundErrCnt", None)
            if rc == 0 and counter is not None:
                rc = 1 if counter(cs) > 0 else 0
        drain()
        if rc == 0 and getattr(lib, "csoundErrCnt", None) is None:
            # ONLY where the counter is missing, and this `if` is the whole point
            # of the line: `drained` holds the BODY's output too, and a body is
            # arbitrary model text that may `prints` anything, including the
            # sentence being matched. Reading it where the counter already
            # answered would let a body talk this gate into rejecting it — a
            # verdict that would differ between an install with a Csound CLI and
            # one without, which is the one property a gate may not have.
            # The LAST match, for the same reason: Csound's own count is printed
            # by csoundCleanup, after everything the body ever prints.
            hits = re.findall(r"(\d+)\s+errors? in performance", "".join(drained))
            if hits and int(hits[-1]) > 0:
                rc = 1
    finally:
        lib.csoundDestroyMessageBuffer(cs)
        lib.csoundDestroy(cs)
    # Csound's words go to stderr because that is where the CLI puts them and
    # where _explain_perf reads them from.
    if drained:
        sys.stderr.write("".join(drained))
        sys.stderr.flush()
    return 0 if rc == 0 else 1


def _render_command():
    """The argv prefix that performs a CSD, or None when nothing here can.

    An installed CLI first — it is a plain binary with no interpreter to start,
    and on a developer machine it is already there. Otherwise this app itself,
    through `render_child_main`. Both are a separate process holding the same
    compiler the engine holds; the caller appends Csound options and a path and
    cannot tell them apart."""
    binary = _csound_binary()
    if binary is not None:
        return [binary]
    lib = _csound_library()
    if lib is None or not hasattr(lib, "csoundPerformKsmps"):
        return None
    if getattr(sys, "frozen", False):
        return [sys.executable, RENDER_FLAG]
    # Source tree: the frozen bundle's single entry point is this module's
    # neighbour, and it dispatches the flag before it imports anything heavy.
    entry = Path(__file__).resolve().parent / "pipe_inference.py"
    if entry.is_file():
        return [sys.executable, str(entry), RENDER_FLAG]
    return None


# `kx = limit kfreq, 20, 12000` — an opcode STATEMENT written as an assignment.
# It is the author's single most frequent mechanical slip and the one it cannot
# see: Csound answers with a positional complaint ("unexpected NEWLINE, expecting
# ',' or ')'") that names neither the `=` nor the opcode, so the author reads it
# as a bracket problem, rewrites the arguments, and produces the same shape
# again. Measured on "accordeon > guitar": six attempts, three different lines,
# every one of them this. It appears most when the author RENAMES variables to
# keep two morph ends apart (`kstr` -> `kstr_g`) and reformats the line while
# doing so — the library's own `name<spaces>opcode args` is visually an
# assignment, and the `=` creeps in.
#
# Detection is syntactic and needs no opcode list: after `=`, an identifier
# followed by SPACE and then something that is not an operator is an opcode
# statement, never arithmetic. `= a + b` (operator follows), `= foo(x)` and
# `= poscil:k(...)` (no space before the bracket) are all left alone.
_ASSIGNED_OPCODE = re.compile(
    r"^\s*([A-Za-z]\w*)\s*=\s*([A-Za-z]\w*)\s+(?![-+*/%,)=<>&|?:])\S")


# `vco2 kamp, kcps, 1` — the author's second mechanical slip, and the one the
# compiler cannot catch at all. `imode` is a bit sum whose bit 1 means SKIP
# INITIALISATION, so an odd imode compiles cleanly and the opcode then dies at
# the first k-cycle with "vco2: not initialised" — an orchestra that passes every
# parse and makes no sound. The library only ever uses 0 (saw), 2 (pulse/square)
# and 4 (triangle), and 2 and 4 additionally REQUIRE the kpw argument; the `1` is
# invented. Measured 2026-07-24 on the first prompt of tools/lco_morph_corpus.txt.
_VCO2_CALL = re.compile(r"^\s*\w+\s+vco2\s+(.*)$", re.IGNORECASE)

# `kbow    0.8` — the mirror of the stray `=`: an assignment written WITHOUT one.
# Csound reads the variable as an opcode name and complains about the number
# after it ("unexpected NUMBER_TOKEN"), naming neither the variable nor the
# missing `=`. Measured 2026-07-24 on `a bowed cello`, where it cost the whole
# authoring: the author reproduced the line and the loop stopped. Detection is
# narrow on purpose — a Csound variable prefix, then nothing but a number to the
# end of the line. No library line and no scaffold line but `instr 1` has that
# shape, and the hint is only ever attached to a line Csound already rejected.
_BARE_ASSIGN = re.compile(r"^\s*([akig][A-Za-z0-9_]*)\s+(-?\d+(?:\.\d+)?)\s*(?:;.*)?$")
_NOT_A_VARIABLE = frozenset(("instr", "endin", "igoto", "kgoto", "opcode", "endop"))


def _split_args(text):
    """Top-level comma split — `foo(a, b)` and `(x * y)` stay one argument."""
    out, depth, cur = [], 0, ""
    for ch in text:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth = max(0, depth - 1)
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    out.append(cur.strip())
    return out


def _vco2_imode_hint(line):
    """`vco2`'s imode, when the line names one Csound will not play."""
    m = _VCO2_CALL.match(line or "")
    if not m:
        return ""
    args = _split_args(m.group(1).split(";")[0])
    if len(args) < 3 or not re.fullmatch(r"\d+", args[2]):
        return ""
    imode = int(args[2])
    if imode % 2 == 1:
        return (f" — `vco2`'s imode is a BIT SUM, and bit 1 means \"skip "
                f"initialisation\": with {imode} the oscillator is never "
                f"initialised and produces nothing, which is why this only "
                f"fails at performance and not at compile time. The waveforms "
                f"are 0 (sawtooth), 2 (pulse/square) and 4 (triangle); 2 and 4 "
                f"take the duty cycle as a fourth argument.")
    if imode in (2, 4) and len(args) < 4:
        return (f" — `vco2` imode {imode} needs the pulse width as a FOURTH "
                f"argument (`vco2 kamp, kcps, {imode}, kpw`); without it the "
                f"note is deleted at init and nothing sounds.")
    return ""


def _mechanical_hint(line):
    """The one edit that fixes this line, named — never a rewritten line.

    Python does not author Csound here and must not start: it says WHICH
    character is wrong and why, and the model writes the correction. That is the
    same division the repair turn already keeps (Python names the compiler's
    complaints, the model writes the fix) — only precise enough to act on.

    Each recognised slip is one Csound FACT the compiler's own message does not
    state — "brackets" for a stray `=`, "not initialised" for an odd `vco2`
    imode. Without the fact named, the author reads the complaint literally and
    repairs the wrong thing until the loop stops."""
    m = _ASSIGNED_OPCODE.match(line or "")
    if not m:
        b = _BARE_ASSIGN.match(line or "")
        if b and b.group(1).lower() not in _NOT_A_VARIABLE:
            return (f" — this line gives `{b.group(1)}` a value, and a value needs "
                    f"an `=`: `{b.group(1)} = {b.group(2)}`. Without it Csound reads "
                    f"`{b.group(1)}` as an opcode name, which is why it complains "
                    f"about the number that follows rather than about the line.")
        return _vco2_imode_hint(line)
    var, opcode = m.group(1), m.group(2)
    return (f" — `{opcode}` is an OPCODE, so this line is a statement, not an "
            f"assignment: the `=` after `{var}` must go. Csound's complaint about "
            f"brackets is a consequence of that `=`, not a bracket problem; "
            f"changing the arguments will not fix it.")


def _explain(log, orchestra):
    """Csound's own complaint, plus the line of the AUTHORED body it points at.

    Csound reports positions in the wrapped CSD. The author wrote only the body
    and has never seen the wrapper, so a bare "Line 49" is unusable to it —
    quoting its own line back is what makes the repair round actually repair.
    """
    msgs, quoted = [], []
    csd_lines = orchestra.splitlines()
    for ln in _CTRL.sub("", _ANSI.sub("", log)).splitlines():
        if _ERR_LINE.search(ln):
            # drop Csound's "from file /tmp/....csd (1)," prefix: a temp path is
            # noise in the repair turn, and the author cannot act on it.
            msgs.append(re.sub(r"^.*?from file .*?,\s*", "", ln.strip()))
            continue
        e = _ECHO.search(ln)
        if e and e.group(1).strip():
            src = e.group(1).strip()
            quoted.append(f"your line: {src}{_mechanical_hint(src)}")
            continue
        m = _LINE_NO.match(ln)
        if m:
            n = int(m.group(1))
            src = csd_lines[n - 1].strip() if 0 < n <= len(csd_lines) else ""
            if src and n > _BODY_OFFSET:
                quoted.append(f'your line: {src}{_mechanical_hint(src)}')
    if not msgs:
        tail = [l for l in log.strip().splitlines() if l.strip()]
        msgs = [tail[-1]] if tail else ["csound failed without a message"]
    # de-duplicate while keeping order: the same error is often echoed per pass
    seen, parts = set(), []
    for part in msgs + quoted:
        if part not in seen:
            seen.add(part)
            parts.append(part)
    return "; ".join(parts[:4])


# Csound's RUNTIME complaints. They do not match `_ERR_LINE` (there is no colon
# after "ERROR") and they carry the line inline rather than on a line of their
# own, so `_explain` cannot read them — a separate shape for a separate pass.
_PERF_ERR = re.compile(r"\b(?:PERF|INIT)\s+ERROR\b.*", re.IGNORECASE)
_PERF_LINE = re.compile(r"\bline\s+(\d+)\b", re.IGNORECASE)


def _explain_perf(log, csd, body_offset):
    """A runtime failure, with the author's own line quoted back at it.

    Same division as `_explain`: Csound's words, plus the line of the BODY they
    point at. `_mechanical_hint` rides along because a runtime error can have the
    same cause as a parse error.

    Quotes from the CSD that was actually RUN, and takes its body offset — the
    performance check adds lines above the body, so the offset `_explain` uses
    would point at the wrong line here. The body itself is copied verbatim, so
    the quoted text is the author's own either way."""
    csd_lines = csd.splitlines()
    clean = _CTRL.sub("", _ANSI.sub("", log))
    parts, seen = [], set()
    for ln in clean.splitlines():
        m = _PERF_ERR.search(ln)
        if not m:
            continue
        msg = m.group(0).strip()
        n = _PERF_LINE.search(msg)
        if n:
            i = int(n.group(1))
            src = csd_lines[i - 1].strip() if 0 < i <= len(csd_lines) else ""
            if src and i > body_offset:
                msg = f"{msg}; your line: {src}{_mechanical_hint(src)}"
        if msg not in seen:
            seen.add(msg)
            parts.append(msg)
    if not parts:
        tail = [l for l in clean.strip().splitlines() if l.strip()]
        parts = [tail[-1]] if tail else ["csound failed during performance"]
    return "; ".join(parts[:4])


def perform_check(orchestra):
    """(ok, first_error) — does this orchestra actually PLAY?

    A gate that only parses is not the thing that later judges. `vco2 kamp,
    kcps, 1` parses (imode bit 1 is "skip initialisation"), compiles, and then
    dies at the first k-cycle with "vco2: not initialised"; `vco2 ..., 2` without
    its kpw parses and deletes the note at init. Both reach the engine as a
    successful authoring and are heard as silence, with nothing anywhere saying
    why (measured 2026-07-24, first prompt of tools/lco_morph_corpus.txt).

    So the check runs the instrument — the real wrapped orchestra, all 16 voices,
    against a score shortened to a fraction of a second. ~0.1 s. Csound's own exit
    code is the verdict, and its own message is what goes back to the author.

    In a CHILD, always: performing means `csoundStart`, and doing that in-process
    would run an authored orchestra inside the backend that holds the model. The
    child is an installed CLI where there is one and this app itself where there
    is not (`_render_command`) — until 2026-08-04 it could only be the CLI, and
    since no app bundle contains one, this check silently returned "fine" on
    every install that has no Homebrew Csound. Only where nothing at all can
    perform does it still return (True, "") — unchecked, never falsely failed."""
    command = _render_command()
    if command is None:
        return True, ""
    # Cut at the LAST `<CsScore>`, not by pattern search: the authored body sits
    # above it and is arbitrary model output, so a comment containing the tag
    # would otherwise capture the substitution and silently truncate the
    # instrument — a compile failure this gate would then report as a runtime one.
    head, sep, _ = orchestra.replace("%SR%", "44100").rpartition("<CsScore>\n")
    if not sep:
        return True, ""     # not this module's scaffold; nothing to judge
    # Play a real note. With no host nothing writes the per-voice channels, so
    # `chnget` reads 0 and `kfreq limit …, 20, 12000` pins every voice to 20 Hz —
    # the bottom of the scaffold's own clamp. That is a legitimate pitch, but it
    # is not the one this orchestra will mostly be played at, and a body whose
    # delay line or table index depends on frequency would be judged somewhere
    # else than where it runs. Inserted at a marker the scaffold owns; the
    # authored body sits AFTER it, so a body quoting the same line cannot capture
    # the substitution (str.replace takes the first, which is the scaffold's).
    marker = 'chnset 1.0000, "osc3oct"\n'
    presets = "".join(f'chnset {v}, "{c}{i}"\n'
                      for c, v in (("freq", 220.0), ("gate", 1.0), ("vel", 0.8))
                      for i in range(1, NCHNLS + 1))
    inserted = 0
    if marker in head:
        head = head.replace(marker, marker + presets, 1)
        inserted = presets.count("\n")
    score = "".join(f"i 1 0 {_PERF_SECS} {v}\n" for v in range(1, NCHNLS + 1))
    csd = f"{head}{sep}{score}e {_PERF_SECS}\n</CsScore>\n</CsoundSynthesizer>\n"
    fh = tempfile.NamedTemporaryFile("w", suffix=".csd", delete=False,
                                     encoding="utf-8", errors="replace")
    path = fh.name
    try:
        with fh:
            fh.write(csd)
        # -n: render nothing to a device. -d: no graphs. -m0: no per-note stats.
        r = subprocess.run(command + ["-n", "-d", "-m0", path],
                           capture_output=True, timeout=90,
                           env=_csound_child_env())
        if r.returncode == 0:
            return True, ""
        if r.returncode in _RENDER_ENV_FAULT:
            # The child could not put the question, so there is no answer about
            # this orchestra. Handing it back as a verdict would show the author
            # an install instruction as if it were a Csound diagnostic and send
            # it round the repair loop five more times over code that may be
            # perfectly good — the very thing the syntax gate raises
            # CompilerUnavailable to prevent.
            print(f"lco_write: perform check could not run: "
                  f"{_decode(r.stderr).strip()[:200]}", file=sys.stderr, flush=True)
            return True, ""
        return False, _explain_perf(_decode(r.stderr) + _decode(r.stdout), csd,
                                    _BODY_OFFSET + inserted)
    except subprocess.TimeoutExpired:
        # A body that cannot render a quarter of a second in 90 s cannot be
        # played by the engine either. Naming it as what it is beats a silent pass.
        return False, ("this orchestra did not finish rendering a fraction of a "
                       "second in 90 seconds — something in it does not run in "
                       "real time")
    except OSError as exc:
        # Same reasoning as the syntax gate's spawn failure: an environment that
        # cannot fork must not be reported as the author's mistake.
        print(f"lco_write: perform check could not run {command[0]}: {exc}",
              file=sys.stderr, flush=True)
        return True, ""
    finally:
        try:
            os.unlink(path)
        except OSError:
            pass


# ─────────────────────────────────────────────────────────────────────────────
# The knob gate — does turning it change the sound?
# ─────────────────────────────────────────────────────────────────────────────
# `read_controls` asks whether the body READS the variable. That is a textual
# question and it is one step short of the promise the panel makes: a variable
# can be read into an expression that reaches nothing audible, and the slider is
# then still under the player's hand. Measured 2026-08-03 on a `bell` the author
# was given no line to keep and no code exemplar for — five of the library's 49
# declared parameters are in that state — and `ring` and `detune` came back as
# sliders that moved nothing while `index`, the one axis of the three with an
# `anchor_code` exemplar, worked.
#
# So this gate stops asking and RENDERS: the orchestra as it will play, once at
# the position the author put the knob and once at each end of its travel. If not
# one sample moved, the knob is withheld. The test is threshold-free on purpose —
# "changes no sample of the output" needs no theory of hearing and no number this
# file would have to defend (`tools/lco_param_audit.py` calls the same category
# the only kind of finding that is valid without one). A knob that does anything
# at all passes; judging how MUCH it does is BJ's ear, not this.
#
# WHERE a knob is judged, and it has to be where the INSTRUMENT actually runs.
# `perform_check` writes three channels and leaves the rest at zero, which is
# harmless when the only question is whether the orchestra stands up — and wrong
# here, because a body is allowed to use every one of them (`ktimb`, `kpres` and
# `kvel` are offered to the author under AVAILABLE IN SCOPE). At zero, `ktimb`
# multiplies whatever it touches to nothing, and a knob behind it renders
# identically at every position: measured, a `warble` scaled by `ktimb` was taken
# off the panel while it worked perfectly in the plugin.
#
# That measurement was made when the plugin's timbre rested at 64/127. It does
# not any more: MPE's Y axis is an absolute travel from rest, measured 0 at rest
# on the Osmose, so `SynthVoice::kTimbreRest` is 0.0 and the first point follows
# it (2026-08-23). Which puts point one back on the value that makes a
# ktimb-scaled knob look dead — deliberately, because that IS where the player
# finds the instrument before touching anything, and because the rule below is
# BOTH points: point two sits at the top of the timbre travel and catches every
# knob of that kind. What would be wrong is probing a Y position no untouched
# note produces and calling the result the plugin's behaviour.
#
# So: the plugin's own resting values, and then a SECOND point, because one
# operating point can only ever say "dead here". The second is a different
# register, a different velocity, under pressure and at the top of the timbre
# travel, and it runs twice as long — the four dimensions a knob was measurably
# alive in while the first point called it dead. A knob is withheld only when
# every probe at BOTH points renders identically to that point's baseline.
#
# The second point is nearly free: a knob that moves the sound leaves at its
# first probe, so only knobs that already look dead are ever rendered there.
# FOUR SECONDS for the first, because that is what `tools/lco_measure.py` renders
# and what every measurement on this platform is read over; eight for the second,
# for an axis that takes its time (`ring` runs to 5.5 s).
_KNOB_POINTS = (
    {"secs": 4.0, "freq": 220.0, "vel": 0.80, "pres": 0.0,
     "timb": 0.0, "voice": 1},
    {"secs": 8.0, "freq": 880.0, "vel": 0.35, "pres": 0.7,
     "timb": 1.0, "voice": 5},
)
# The two points are ALSO two different voices, because `ivoice` is a dimension
# like the others and the system prompt tells the author to use it ("give each
# voice its own phase or seed so a chord does not move in lockstep"). Held at 1,
# `(ivoice - 1)` is zero and a knob that spreads a stack across the voices does
# nothing at all — measured: a `detune` doing exactly that was taken off the panel
# while it worked on every voice but the first.
#
# THE NOTE IS AN EDGE, not a level. `changed2(ktrig)` is how a body knows a note
# began — three library entries reinitialise on it — and a channel written once
# before the instrument starts never changes, so it never fires and a knob behind
# it is judged in a body that thinks it has not been played yet. So gate and trig
# are rewritten to rise at `_KNOB_ONSET`, which is what `tools/lco_measure.py`
# does with its preroll and for the same reason. Far above two k-periods at any
# rate this gate renders at.
_KNOB_ONSET = 0.01
# Where a knob is put to see whether the sound follows. The two ENDS, because an
# axis with a `min`, a `limit` or a clamped index has stretches where it does
# nothing and a body may well sit in one — and the MIDDLE, because both ends of
# an axis folded around its centre (`0.5 - abs(k - 0.5)` and everything like it)
# read alike while the travel between them does not. The author's own position is
# dropped from the list: it IS the baseline, and comparing it with itself would
# call every knob that starts at 0.0 dead.
_KNOB_PROBES = (0.0, 0.5, 1.0)
# The head's own `chnset` line for one knob channel, which is what a render moves.
# Anchored at column 0: `wrap` indents the authored body by two spaces, so a body
# that writes the same line for itself cannot be caught by this.
_HEAD_CHNSET = r'^chnset[ \t]+[-+0-9.eE]+,[ \t]*"{ch}"[ \t]*$'


# A float32 whose exponent bits are all ones is a NaN or an infinity, and in
# little-endian bytes that is visible in the high byte of each four: bits 6..0 of
# it are the top seven exponent bits. This table marks those bytes so a whole
# render can be tested for them with two C-speed passes instead of eleven million
# Python floats. It also marks the largest finite exponent, which is the
# conservative direction: it can only make this gate go quiet.
_NONFINITE_HIGH_BYTE = bytes(1 if (v & 0x7f) == 0x7f else 0 for v in range(256))


def _fingerprint(path):
    """(digest of the rendered samples, whether any of them is not finite).

    A DIGEST, not the samples. One render at the rate this gate uses is 45 MB of
    raw floats and the second point is 90, three of which were alive at once —
    426 MB peak, in the process that also holds the inference model. Nothing here
    needs the samples themselves: the question is only whether two renders are the
    same, and comparing digests answers exactly that at a few megabytes.

    THE NOT-FINITE FLAG is the same pass's other half, and what it is for has to
    be said precisely because the obvious story is wrong. A body that puts a NaN
    into its sum does NOT arrive here as NaN: the scaffold's own `clip` in `_TAIL`
    turns it into a constant (measured: -0.87875 for every sample of the note), so
    what such a body actually renders is a body with no sound in it, every knob
    genuinely changes nothing, and "every knob is dead" is a true sentence about
    it — the fault is upstream, in a perform check that passes an orchestra whose
    output is a DC level. The flag guards the case the clip does not catch: a
    render that reaches the file not finite is garbage, not a body whose knobs do
    nothing, and this gate must not spend a verdict on it."""
    digest, poisoned = hashlib.sha256(), False
    with open(path, "rb") as fh:
        while True:
            # A multiple of four, so every chunk starts on a sample boundary and
            # `[3::4]` is the high byte of each float and not a rotation of it.
            chunk = fh.read(1 << 22)
            if not chunk:
                break
            digest.update(chunk)
            poisoned = poisoned or b"\x01" in chunk[3::4].translate(
                _NONFINITE_HIGH_BYTE)
    return digest.digest(), poisoned


def _knob_render(command, orchestra, overrides, point):
    """This orchestra at one operating `point`, fingerprinted, or None.

    ONE voice, not the sixteen `perform_check` plays: they all render the same
    thing here (nothing writes the per-voice channels differently), so fifteen of
    them are the same measurement again at sixteen times the cost. The voice is
    p4=1 because several library bodies decorrelate on `ivoice`, and a comparison
    has to hold that fixed like everything else.

    Headerless floats (`-h -f`), so what comes back is samples and only samples —
    a WAV header is a place for two identical renders to differ over nothing.

    None on ANY failure, and the caller then withholds no knob: this runs after
    `perform_check` has already passed, so a body that trips over a longer score
    is a fact about this gate's own window and must never be dressed up as a
    verdict on the author's knob."""
    # AT THE RATE THE INSTRUMENT RUNS AT, which is not 44100. The engine compiles
    # Csound at the host's rate times the LRO's oversampling — 4 by default
    # (`PluginProcessor.h`, lroOsFactor_) — and this project has already paid for
    # the difference: `dcblock2`'s corner scales with sr, `wgpluck2`'s ring length
    # moves by more than a decade between 1x and 4x, and `singing_bowl`'s own
    # comment records a 6.09x peak between exactly these two rates. `perform_check`
    # may use 44100 because it only asks whether the body runs at all; a gate that
    # takes a control away from the player has to look at the instrument the
    # player has. 176400 is that default over the standard rate — a session at
    # another host rate or another oversampling setting is a nearer neighbour of
    # this than of 44100.
    head, sep, _ = orchestra.replace("%SR%", "176400").rpartition("<CsScore>\n")
    if not sep:
        return None                     # not this module's scaffold
    # The scaffold renders to nothing by default; this gate needs the samples.
    # Replaced in the CSD rather than overridden on the command line because
    # `-n` has no negation — and `-o` goes on the command line rather than into
    # the CSD because a temp path with a space in it is one token there and two
    # inside `<CsOptions>`.
    options = "<CsOptions>\n-n -d\n</CsOptions>"
    if options not in head:
        return None
    head = head.replace(options, "<CsOptions>\n-d\n</CsOptions>", 1)
    # A real note, played the way the plugin plays one (see `_KNOB_POINTS`): with
    # nothing writing the per-voice channels every voice would sit at the bottom
    # of the scaffold's own clamp with its timbre at zero, and a knob that depends
    # on either would be judged where the instrument never runs.
    #
    # A MISSING MARKER IS NOT A PASS. `perform_check` can shrug this off — it
    # only means the body is checked at 20 Hz instead of 220 — but here the note
    # would never open, every render would be the same silence, and this gate
    # would take the player's whole panel away on the strength of a substitution
    # that did not happen.
    marker = 'chnset 1.0000, "osc3oct"\n'
    if marker not in head:
        return None
    presets = "".join(f'chnset {point[c]}, "{c}{i}"\n'
                      for c in ("freq", "vel", "pres", "timb")
                      for i in range(1, NCHNLS + 1))
    head = head.replace(marker, marker + presets, 1)
    # Gate and trig are not channels here but an EDGE (see `_KNOB_ONSET`). Both
    # lines are the scaffold's own and stand above the body; if either is not
    # there this is not the scaffold and there is nothing to judge.
    edge = f"(timeinsts() >= {_KNOB_ONSET} ? 1 : 0)"
    for old, new in (("  kgateraw chnget Sgate\n", f"  kgateraw = {edge}\n"),
                     ("  ktrig    chnget Strig\n", f"  ktrig    = {edge}\n")):
        if old not in head:
            return None
        head = head.replace(old, new, 1)
    for ch, value in (overrides or {}).items():
        head, n = re.subn(_HEAD_CHNSET.format(ch=re.escape(ch)),
                          f'chnset {value:.4f}, "{ch}"', head, count=1,
                          flags=re.MULTILINE)
        if n != 1:
            return None                 # the channel this knob rides on is gone
    csd = (f"{head}{sep}i 1 0 {point['secs']} {point['voice']}\n"
           f"e {point['secs']}\n</CsScore>\n</CsoundSynthesizer>\n")
    # Inside the guard, not above it: a temp directory that cannot be made is an
    # environment fault like a fork that fails, and this whole gate is allowed to
    # go quiet — but it is NOT allowed to raise, because it runs after a
    # successful authoring and would take the finished orchestra down with it.
    try:
        work = tempfile.mkdtemp(prefix="t5ynth-knob-")
    except OSError:
        return None
    csd_path, raw_path = os.path.join(work, "k.csd"), os.path.join(work, "k.raw")
    try:
        with open(csd_path, "w", encoding="utf-8", errors="replace") as fh:
            fh.write(csd)
        # Bytes, not `text=True`: nothing here reads the child's message, and
        # decoding it strictly would let one non-UTF-8 byte out of Csound raise a
        # UnicodeDecodeError — a ValueError, which the handler below does not
        # catch — straight through a gate that runs AFTER a successful authoring.
        # The finished orchestra would come back as ok=false over a stray byte.
        # `-o<path>` glued, not `-o path`: Csound's own csoundSetOption takes one
        # option per call and rejects a blank, so the child in render_child_main
        # could not put a split pair back together without knowing which flags
        # carry a value. The CLI has accepted the glued form since forever, so
        # both children get the identical argument list.
        r = subprocess.run(command + ["-d", "-m0", "-h", "-f", f"-o{raw_path}",
                            csd_path], capture_output=True,
                           timeout=90, env=_csound_child_env())
        if r.returncode != 0:
            return None
        return _fingerprint(raw_path)
    except (subprocess.TimeoutExpired, OSError):
        return None
    finally:
        shutil.rmtree(work, ignore_errors=True)


def dead_knobs(orchestra, controls):
    """{line ordinal: why} for every knob that changes no sample of the sound.

    Empty when they all do something, and empty as well whenever the question
    could not be put — no compiler, no knobs, a body that will not render twice
    the same way. Absence of data is not a verdict: withholding a working knob
    takes a control out of the player's hand as surely as a dead one leaves a
    useless one in it, so everything here fails towards keeping the knob.

    THE BODY IS ASKED WHETHER IT IS DETERMINISTIC FIRST, by rendering the
    baseline twice. Several library bodies are built on noise, and one that
    reseeds per run differs from itself — every knob would then "move" it and
    this gate would pass everything while reading as a check. That is the
    failure mode a gate must not have, so a body that does not reproduce is
    reported as unmeasurable (here: an empty result) rather than as clean.

    MORE THAN ONE POSITION, and never only one end: see `_KNOB_PROBES` for which
    and why. MORE THAN ONE OPERATING POINT, for the same reason one position is
    not enough: see `_KNOB_POINTS`. A knob counts as dead only when every probe
    at every point renders identically to that point's baseline, and each loop
    leaves at the first render that does not.

    The comparison is on the render's BYTES, which is very slightly stricter than
    the sentence above: +0.0 and -0.0 are the same sample and different bytes. It
    errs towards keeping the knob, which is the direction this whole function errs
    in — as does a render that is not finite, which is thrown out rather than read
    as a body whose knobs all do nothing (see `_fingerprint`)."""
    params = list((controls or {}).get("params", ()))
    if not params:
        return {}
    command = _render_command()
    if command is None:
        return {}
    # One baseline per point, made only when a knob actually reaches that point —
    # the second one is never rendered for a body whose knobs all move the sound.
    # None means "not measurable here", and every caller reads that as: keep it.
    bases = {}
    def baseline(i):
        if i not in bases:
            first = _knob_render(command, orchestra, {}, _KNOB_POINTS[i])
            again = (_knob_render(command, orchestra, {}, _KNOB_POINTS[i])
                     if first else None)
            bases[i] = (first[0] if first and not first[1] and first == again
                        else None)
        return bases[i]

    dead = {}
    for k in params:
        probes = [p for p in _KNOB_PROBES if abs(k["value"] - p) > 1e-6]
        moved = False
        for i in range(len(_KNOB_POINTS)):
            base = baseline(i)
            if base is None:
                moved = True            # unmeasurable here: no verdict, keep it
                break
            for probe in probes:
                out = _knob_render(command, orchestra, {k["ch"]: probe},
                                   _KNOB_POINTS[i])
                if out is None or out[0] != base:
                    moved = True
                    break
            if moved:
                break
        if not moved and probes:
            dead[k["line"]] = ("turning it changes no sample of the sound — the "
                               "line stands in the body and the variable is read, "
                               "but nothing it reaches comes out")
    return dead


def gate_knobs(body, orchestra, controls):
    """(orchestra, controls) with every knob that moves nothing withheld.

    The orchestra is rebuilt because the wiring is part of it: a withheld knob
    gets its own number back in the line — the one the author wrote, which is
    also the position the baseline render just proved the sound to be at — and
    the knobs that survive move up into the freed channels.

    UNTIL NOTHING NEW DIES, because withdrawing one knob can ADMIT another:
    `read_controls` refuses a fourth column and a fifth knob in a column, and a
    line that was over that limit comes in as soon as a column empties out — a
    knob that has then never been rendered. The loop cannot run away: every round
    adds at least one line to `skip` and there are only so many lines.

    AND THE REBUILT ORCHESTRA IS PUT THROUGH BOTH GATES AGAIN, which the first
    version of this argued was unnecessary. It is not. A knob that is WITHHELD
    goes from `0 + 1 * kp1a` back to the author's own number and can break
    nothing — but a knob that is PROMOTED goes the other way, and that line
    reaches the wiring here for the first time: everything upstream only ever saw
    it as a plain number. Worse than a compile risk, it does not carry the same
    value — `wire_controls` rewrites it to `lo + span * kp` and the position is
    baked as a decimal, so a line the author wrote as `age = 1.00` comes back as
    0.9999 and an `int()` in the body reads 0. If the rebuild does not stand up,
    the SOUND wins and the panel keeps the knobs it had: a slider that lies is a
    smaller failure than an instrument that does not play. What was measured is
    still SAID, in `refused` beside the knob it did not manage to withdraw —
    dropping a verdict because it could not be acted on is how a decision stops
    travelling with the sound."""
    skip = {}
    for _ in range(max(1, len(_param_lines(body or "")))):
        dead = dead_knobs(orchestra, controls)
        if not dead:
            break
        skip.update(dead)
        pruned_controls = read_controls(body, skip=skip)
        pruned = wrap(wire_controls(body, pruned_controls), pruned_controls)
        try:
            ok, _ = syntax_check(pruned)
        except CompilerUnavailable:
            # The compiler went away between the render and here. Not a verdict
            # about the rebuild, and treated like a failed one for the same
            # reason: without a check there is nothing to stand on.
            ok = False
        if ok:
            ok, _ = perform_check(pruned)
        if not ok:
            kept = dict(controls)
            kept["refused"] = list(controls.get("refused", ())) + [
                f"{n} — measured dead, and kept anyway: the body no longer "
                f"stands up once the wiring is rebuilt without it"
                for n in sorted(_names_of(controls, dead))]
            return orchestra, kept
        orchestra, controls = pruned, pruned_controls
    return orchestra, controls


def _names_of(controls, lines):
    """The player-facing names of the knobs sitting on those body lines."""
    return {p["name"] for p in (controls or {}).get("params", ())
            if p["line"] in lines}


def syntax_check(orchestra):
    """(ok, first_error). Runs the real compiler over the real orchestra, so the
    gate is Csound's own verdict rather than a parser of ours guessing at one.
    sr is substituted for the check only.

    Raises CompilerUnavailable when there is no compiler to ask. That is an
    environment fault, not an authoring one: it must not be dressed up as a
    Csound diagnostic and fed back to the model, and no retry can repair it."""
    csd = orchestra.replace("%SR%", "44100")
    binary = _csound_binary()
    if binary is not None:
        try:
            return _check_via_cli(binary, csd, orchestra)
        except OSError as exc:
            # The binary vanished between lookup and run, or no process could be
            # spawned at all (ENOMEM/EMFILE next to a resident multi-GB model).
            # The in-process compiler needs no fork, so try it before giving up —
            # refusing to author while a working Csound sits in this very process
            # would be the wrong answer to a fork that failed.
            spawn_error = f"could not run {binary}: {exc}"
    else:
        spawn_error = None

    try:
        ok, log = _check_via_library(csd)
    except CompilerUnavailable:
        # Neither route worked. Prefer the spawn failure's own errno over the
        # generic "nothing installed": one of them is actionable.
        if spawn_error:
            raise CompilerUnavailable(spawn_error) from None
        raise
    return (True, "") if ok else (False, _explain(log, orchestra))


def _check_via_cli(binary, csd, orchestra):
    """(ok, first_error) from the Csound CLI in its own process. Lets OSError
    through: the caller decides whether an unspawnable compiler is fatal."""
    # encoding is explicit: an authored comment can carry any codepoint, and the
    # platform default (cp1252 on Windows) would raise mid-write, leaking the
    # temp file and escaping every handler here as a bare ValueError. The
    # in-process path encodes UTF-8, so this also keeps the two paths agreeing.
    fh = tempfile.NamedTemporaryFile("w", suffix=".csd", delete=False,
                                     encoding="utf-8", errors="replace")
    path = fh.name
    try:
        with fh:
            fh.write(csd)
        r = subprocess.run([binary, "--syntax-check-only", path],
                           capture_output=True, timeout=90,
                           env=_csound_child_env())
        if r.returncode == 0:
            return True, ""
        return False, _explain(_decode(r.stderr) + _decode(r.stdout), orchestra)
    except subprocess.TimeoutExpired:
        return False, "csound syntax check timed out"
    finally:
        try:
            os.unlink(path)
        except OSError:
            pass



def _consult(user_turn, sysp, llm, on_thinking=None):
    """The author's own consultation: it reads the shelf and says what it wants.

    Returns `(raw_reply, named, thinking)` — the reply verbatim, so the writing
    turn can continue the same conversation; the entries `named_entries`
    recognised in it; and its reasoning, which is now the ONLY place the author
    says what it thinks this sound is (the writing turn is asked not to reason
    again, so nothing kept here leaves the panel with an empty THINKING). A reply
    that names nothing is not an error and is not overridden: the caller opens
    the whole library, which is the only answer that does not put Python in
    charge of what the author may see.

    The reasoning goes out live under attempt 0. It is the same THINKING the
    panel has always shown, arriving earlier — this IS the author choosing, and
    it would be perverse to hide the one turn that is nothing but reasoning."""
    watcher = _live_watch(on_thinking, None, 0)
    turn = user_turn + _CONSULT_TURN
    raw = llm(turn, sysp, None) if watcher is None else llm(turn, sysp, None, watcher)
    if watcher is not None:
        watcher.flush()
    # Read the author's own words, not the user's. A consultation that answered
    # with code anyway (it was asked not to) still names its entries in prose
    # above the fence, and the fenced code is not evidence of a choice — it is a
    # body written without the pages, which the next turn replaces.
    body, _, thinking = sanitize(raw)
    # A consultation normally has NO fence, and `sanitize` then hands the whole
    # reply back as the body — so the author's prose is in `body`, not in
    # `thinking`. Taking `thinking` alone would silently read nothing here.
    prose = thinking.strip() or body.strip()
    return raw, named_entries(prose or raw), prose


def _writing_turn(sel):
    """The pages the author asked for, as the turn that asks it to write."""
    return _WRITING_HEAD + render_library(sel) + _WRITING_TAIL


def _continue(base, prev_raw, seen_errors):
    """The repair as a CONTINUATION of the same conversation.

    `base` is the conversation up to and including the turn that asked for the
    body — the request, the author's consultation, and the pages it asked for.
    Appended to it: the author's own failed answer and the compiler's
    complaints. The author then edits what it wrote instead of writing the whole
    sound again from nothing — it keeps the instrument and the movement it
    already chose, and the reasoning it produced in the consultation stays the
    answer rather than being regenerated on every attempt.

    A caller whose model surface only takes a single string still works:
    `_flatten_turn` folds the list back into one text. Nothing is lost in that
    fallback except the KV-cache saving."""
    repair = _repair_turn(seen_errors).lstrip("\n")
    if isinstance(base, str):
        # A surface that only takes one string still has to carry the failed
        # answer: `_REPAIR_TAIL` tells the author "your own previous attempt is
        # above", and without it that sentence points at nothing and the round
        # is a fresh authoring wearing a repair's words. Same wording
        # `_flatten_turn` uses, so both surfaces say the same thing.
        prev = f"Your previous answer was:\n\n{prev_raw}\n\n" if (prev_raw or "").strip() else ""
        return f"{base}\n\n{prev}{repair}"
    if not (prev_raw or "").strip():
        return list(base) + [{"role": "user", "content": repair}]
    return list(base) + [{"role": "assistant", "content": prev_raw},
                         {"role": "user", "content": repair}]


def _flatten_turn(turn):
    """A message list folded back into one user turn, for a model surface that
    cannot take a conversation. The author's previous answer is quoted inside it,
    so the continuation still says what it means — only the KV cache reuse is
    lost."""
    if isinstance(turn, str):
        return turn
    parts = []
    for m in turn:
        if m["role"] == "assistant":
            parts.append("Your previous answer was:\n\n" + m["content"])
        else:
            parts.append(m["content"])
    return "\n\n".join(parts)


def _repair_turn(seen_errors):
    """The repair user-turn built from EVERY distinct error seen so far, not just
    the latest. A single-error view makes the author oscillate: told to fix line
    A it rewrites and breaks line B, told to fix B it reintroduces A, and at
    temperature 0 that is a permanent 2-cycle no number of retries escapes
    (measured on "bright tone -> dark growl": 6/6 attempts alternated between an
    inline-`poscil` body and a bare-`atone` body). Showing all the constraints at
    once is a NEW turn the model has not been at, and it is still the model that
    writes the fix — Python names the compiler's complaints, never the Csound."""
    lines = "\n".join(f"  - {e}" for e in seen_errors)
    n_label = "this error" if len(seen_errors) == 1 else f"these {len(seen_errors)} errors"
    return _REPAIR_HEAD.format(n_label=n_label, errors=lines) + _REPAIR_TAIL


# ─────────────────────────────────────────────────────────────────────────────
# Sanitising the model's reply
# ─────────────────────────────────────────────────────────────────────────────
# The model is told not to emit a header, a score or an `instr`. It sometimes
# does anyway, and a stray header line would fight the host's own. Strip them
# rather than fail the authoring over a formality; anything that changes the
# SOUND is left untouched.

_STRIP = re.compile(
    r"^\s*(</?Cs\w+|sr\s*=|kr\s*=|ksmps\s*=|nchnls|0dbfs|instr\b|endin\b|"
    r"ftgen\b|\w+\s+ftgen\b|out\b|outs\b|outch\b|i\s+\d|f\s+\d|e\s*$|"
    r"SET\s*:)",
    re.IGNORECASE)

# A knob the author asks the SYNTH to set, written inside the fence beside
# READING. It is not Csound and must never reach the compiler (hence the _STRIP
# arm above); it is read back out of the raw reply by `read_settings`.
_SET = re.compile(r"^\s*SET\s*:\s*([A-Za-z0-9_]+)\s*=\s*(.+?)\s*$",
                  re.IGNORECASE | re.MULTILINE)

# The library's own way of declaring a playable parameter, and the ONE source of
# a knob. It is real Csound — the value the body uses — and its comment is the
# declaration:
#
#     kbowl   = 0.50   ; bowl[0.0..1.0]: which measured bowl the mode series is
#
# The variable belongs to whoever wrote the body; the NAME after the `;` is the
# library's, and `params` in the entry is where it is declared with its range,
# its measurement and its anchors. So the knob is neither invented by the author
# nor reconstructed from the code: it is a library parameter that survived into
# the written body, and the author's only say is the NUMBER — where the knob
# starts.
#
# All four shapes in the library today are read: a name against the bracket
# (`bowl[0.0..1.0]`) or spaced off it (`refl [0.70..0.85]`), a name with a space
# in it (`ratio 2`), and a range that is neither 0..1 nor positive
# (`finetune [-50..50]`, `age [0..3]`).
_LIBPARAM = re.compile(
    r'^(?P<indent>[ \t]*)(?P<var>k\w+)(?P<eq>[ \t]*=[ \t]*)'
    r'(?P<value>[-+]?[0-9]*[.,]?[0-9]+)(?P<semi>[ \t]*;[ \t]*)'
    r'(?P<name>[A-Za-z][A-Za-z0-9_]*(?:[ \t]+[A-Za-z0-9_]+)*)[ \t]*'
    r'\[[ \t]*(?P<lo>[-+]?[0-9]*[.,]?[0-9]+)[ \t]*\.\.[ \t]*'
    r'(?P<hi>[-+]?[0-9]*[.,]?[0-9]+)[ \t]*\][ \t]*:[ \t]*(?P<gloss>.*?)[ \t]*$',
    re.MULTILINE)

# A fence marker on its OWN line. Markers are found individually and never
# PAIRED: pairing is what mis-binds a stray ``` to the wrong block, and the
# author's replies are malformed in exactly that way often enough to matter — an
# unclosed final fence (the body is the last thing written, so it is what a
# stopped generation loses), a sketch quoted mid-thought, a lone closer under a
# body that needed none. Splitting on markers and letting the CONTENT say which
# segment is code survives all three; parity does not.
_FENCE_MARK = re.compile(r"^[ \t]*```[A-Za-z0-9_+#-]*[ \t]*\r?$\n?", re.MULTILINE)
# The same marker with the line-start anchor dropped, for the reply that opens
# its fence at the END of a sentence: "...and it moves as it decays. ```csound".
# _FENCE_MARK finds nothing there, the whole reply becomes one segment, and the
# reasoning is handed to the Csound compiler as code. Used ONLY as a fallback,
# when the strict pattern found no marker at all, so a well-formed reply is
# never split on this looser rule. An inline span ("the ```saw``` idiom") does
# not match: the tag has to run to the end of the line.
_FENCE_TAIL = re.compile(r"```[A-Za-z0-9_+#-]*[ \t]*\r?$\n?", re.MULTILINE)
# Anchored at BOTH ends: a real out call is the whole line. Unanchored, the prose
# the author is now invited to write ("outs aexc first, then the resonator") was
# captured as an output routing and appended as `asig = aexc` — a body that
# compiles and emits the bare excitation instead of the instrument.
_OUT_CALL = re.compile(r"^\s*(?:out|outs|outch)\s+(?:\d+\s*,\s*)?(a\w+)"
                       r"(?:\s*,\s*a\w+)*\s*(?:;.*)?$", re.IGNORECASE)
_READING = re.compile(r"^\s*READING\s*:\s*(.+?)\s*$", re.IGNORECASE | re.MULTILINE)
# A line that carries Csound rather than prose. This has to DISCRIMINATE, not
# merely describe: a pattern like `Word word` matches "A struck bar rings and
# decays." as readily as `asig vco2 0.5`, and since the author is now asked to
# reason at length, prose routinely outnumbers code — so a loose pattern hands
# the compiler English and discards a reply that contained a whole orchestra.
#
# Two requirements, both cheap and both true of essentially every Csound line and
# essentially no English sentence:
#   1. it starts with a Csound VARIABLE — the sigil is the type (a/k/i/f/S, with
#      an optional g for global), not a free identifier,
#   2. it does not end like a sentence (checked separately, after any trailing
#      `;` comment is dropped).
# Block keywords count on their own.
_CODE_LINE = re.compile(
    r"^\s*(?:"
    # aL, aR reverbsc a1, a2, 0.85, 5000 — the trailing [\d,] is what keeps
    # "aexc, kstr and asig are the three stages" out: an English enumeration of
    # variable names is otherwise the same shape, and _ENGLISH_HEAD cannot see
    # it because such a line opens with a content word.
    r"g?[akifS]\w*(?:\s*,\s*g?[akifS]\w*)+\s+[a-z]\w*\s+[^;\n]*[\d,]"
    r"|g?[akifS]\w*\s*=\s*\S"                  # kx = ...
    r"|g?[akifS]\w*\s+[a-z]\w*(?:[\s,(]|$)"   # avar opcode args
    r"|(?:if|else|elseif|endif|until|while|od|kgoto|igoto|then)\b"
    r")")
_SENTENCE_END = re.compile(r"[.!?:]\s*$")
# Lowercase a/k/i/f and capital S are Csound TYPE sigils and also the first
# letter of very ordinary English ("as the bow smears", "keep it below", "So a
# struck bar"). Since HOW TO ANSWER asks the author to answer three questions,
# much of the reasoning arrives as FRAGMENTS, which have no closing full stop
# for _SENTENCE_END to catch. `if` stays out of this list: it is a real Csound
# keyword. Lowercase `s` is not a sigil at all, so "sound"/"since"/"slow" never
# reach here.
_ENGLISH_HEAD = re.compile(
    r"^(?:an?|and|as|at|are|any|also|after|about|another|across"
    r"|i|in|is|it|its|into|instead"
    r"|for|from|first|fast|few|full|finally"
    r"|keep|keeps|kind"
    r"|so|since|slow|slower|some|short|still|second)\b", re.IGNORECASE)
# An English function word standing on its own anywhere in the line. This is
# what separates a SENTENCE ABOUT the code from the code — "aexc is the bow,
# continuous noise" opens with a variable name and carries a comma, so it reads
# as `aexc opcode arg, arg` to any shape-based test, and the author writes lines
# like it constantly now that it is asked to reason. Csound has no such words:
# checked against all 94 library idioms and the host scaffold, nothing is lost.
# `if`, `in`, `then`, `while` and `do` are left out — all real Csound.
_ENGLISH_WORD = re.compile(
    r"(?<![\w.])(?:the|is|are|was|were|be|been|this|that|these|those|and|of"
    r"|with|without|from|it|its|as|because|which|when|would|will|should"
    r"|can|could|does|has|have|had|we|you|they|there|than|but|not"
    r"|all|both|each|more|most|much|very|just|only|also|about|into|onto"
    r"|here|how|why|what|who|whose)(?![\w.])", re.IGNORECASE)


def _codeishness(chunk):
    """How many lines of this segment read as Csound. Only ever compared between
    segments of ONE reply, and only as a last resort — the structure of the reply
    decides first (see _pick_body), because content scoring cannot reliably tell
    a fragment of English from a line of Csound and must not be asked to."""
    n = 0
    for ln in (chunk or "").splitlines():
        s = ln.split(";", 1)[0].rstrip()      # a trailing Csound comment is not the line
        if (not s.strip() or _SENTENCE_END.search(s)
                or _ENGLISH_HEAD.match(s.lstrip()) or _ENGLISH_WORD.search(s)):
            continue
        if _CODE_LINE.match(s):
            n += 1
    return n


def _fence_segments(txt):
    """The reply split on fence-marker LINES, as (start, end, mark_before,
    mark_after) spans over the text BETWEEN markers. Never pairs markers, so an
    odd number of them is not a special case."""
    # _FENCE_TAIL, not _FENCE_MARK: it finds the line-start markers too (they
    # satisfy it), plus the one that opens at the end of a sentence, which the
    # anchored pattern cannot see. Missing that one is not a smaller split, it
    # is NO split — the whole reply becomes one segment and the reasoning goes
    # to the Csound compiler as code.
    marks = list(_FENCE_TAIL.finditer(txt))
    spans, prev_end, prev_mark = [], 0, None
    for m in marks:
        spans.append((prev_end, m.start(), prev_mark, m))
        prev_end, prev_mark = m.end(), m
    spans.append((prev_end, len(txt), prev_mark, None))
    return spans


def _pick_body(segments):
    """Which of those segments is the orchestra.

    The author is told to think first, so the text before the FIRST marker is
    prose and is not a candidate. That much is guaranteed by the prompt. What is
    NOT guaranteed — and what two rewrites of this function got wrong in opposite
    directions — is anything about order or size among the rest:

      - the author quotes the library idiom it is adapting, and that quotation
        is longer than the focused body it becomes, so "biggest wins" ships the
        library's own example as the sound,
      - the author also writes AFTER the block ("asig carries the bowed tone
        into the host", or a plainer one-line variant offered as an
        afterthought), so "last wins" ships the afterthought. Measured: a reply
        whose orchestra compiles clean was handed to the repair loop as English,
        and a one-line `asig oscili` alternative replaced a six-line cello
        without any error anywhere.

    So neither position nor length decides. The CONTRACT does: the system prompt
    requires a `READING:` line inside the fence with the body, and only the body
    ever carries one. A quotation does not (it is the library's code, not this
    sound's), an afterthought does not, and prose does not. The body is the last
    candidate that has both a READING and at least one line of code — the code
    requirement because a READING that landed in the prose must not drag a
    paragraph in with it.

    Only when no candidate has one — the author put the READING outside the
    fence, or the generation stopped before reaching it — does content arbitrate,
    and then by weight: the most code, ties to the later. A trailing fragment
    loses to an orchestra on that measure, which is what "last wins" could not
    do. Segment 0 is reached only if nothing after a marker carries code at all,
    i.e. the author wrote the body before the fence."""
    later = range(1, len(segments))
    for i in reversed(later):
        if _READING.search(segments[i]) and _codeishness(segments[i]):
            return i
    best = max(later, key=lambda i: (_codeishness(segments[i]), i), default=0)
    return best if _codeishness(segments[best]) else 0


# Chat-template control tokens that leak into the reply body (observed on the
# shipped GGUF: "<|channel>thought" / "<channel|>" opening the reasoning). They
# are transport syntax, not the author's words, and printing them in the panel
# would quote the tokeniser as if it were the machine thinking.
_CTRL_TOKEN = re.compile(r"<\|[^<>]{0,40}\|?>|<[^<>|]{0,40}\|>")
# The channel NAME left behind once its marker is gone, alone on its line.
_CHANNEL_NAME = re.compile(r"^\s*(?:thought|thinking|analysis|final|message)\s*$",
                           re.IGNORECASE)
# C0/C1 control bytes (outside \t\n\r) have no legitimate place in the author's
# prose — a floor under _repair_mojibake below, for whatever it cannot
# reconstruct.
_STRAY_CONTROL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f-\x9f]")


# U+2000-U+203F (general punctuation: the dashes/quotes/ellipsis an LLM
# reaches for constantly) is the ENTIRE block whose UTF-8 lead byte is E2 and
# second byte 80 — verified against the block's own bit layout, not assumed.
# Deliberately narrow, not "any multi-byte run": an earlier, broader version
# of this repair (any \x80-\xff run, reversed if it happened to be valid
# UTF-8) was caught by review before it shipped — "4×\xa0oversampling" (a
# real multiplication sign next to a real non-breaking space, both <= U+00FF)
# round-trips to valid-looking nonsense (a Hebrew letter) because byte
# validity alone can't tell a genuine adjacent pair from a mangled one; only
# the SPECIFIC block this bug was actually observed in is safe to reverse
# blind. A real "â" letter followed by two bytes that happen to look like
# UTF-8 continuation bytes is the same theoretical risk, but nothing in this
# app's English prose has ever had a reason to write â directly next to a C1
# control range byte, so the residual is accepted rather than eliminated.
_MOJIBAKE_PUNCT = re.compile(r"\xe2\x80[\x80-\xbf]")


def _repair_mojibake(text):
    """Undo a UTF-8-decoded-as-Latin-1 mangling of typographic punctuation,
    if `text` contains one.

    Observed repeatedly on the streamed reasoning: an apostrophe the author
    wrote as U+2019 (bytes E2 80 99) arrives as three separate characters —
    "â" (U+00E2, Latin-1's reading of the E2 lead byte) followed by two
    invisible C1 controls (U+0080, U+0099, Latin-1's reading of the two UTF-8
    continuation bytes) — so the panel shows "bottleâs" with the ’ gone and an
    orphaned â in its place.

    THE CAUSE IS NOW KNOWN AND FIXED UPSTREAM (2026-08-01), so do not go
    hunting for it again: it was `requests`, in author_api.py, on the EXTERNAL
    author path only — which is why the two live reproductions against the
    local GGUF both came out clean and the hunt kept failing.
    `get_encoding_from_headers` applies HTTP/1.1's ISO-8859-1 default to any
    `text/*` type carrying no charset parameter, and SSE is `text/event-stream`;
    a provider that spelled out `charset=utf-8` was clean and one that did not
    corrupted every dash and apostrophe. author_api._post now pins UTF-8 and
    author_api._sse_lines decodes the bytes itself, with
    tools/author_api_encoding_gate.py holding it there.

    This stays as a FLOOR, not as the fix: a provider can still hand us prose
    that was already mangled on its own side, and the repair is cheap and
    narrow. The three-character shape
    is exactly what Latin-1-decoding those three UTF-8 bytes produces, and
    reversing the two encodes recovers the original character (the same
    technique the `ftfy` library calls `fix_encoding`, scoped down to the one
    Unicode block this bug is known to touch).

    Matched three bytes at a time, at the exact E2 80 xx shape — not any run
    of high bytes — so it cannot merge two unrelated adjacent characters into
    something that happens to decode (see _MOJIBAKE_PUNCT's comment for the
    concrete case that ruled out the broader version). `decode('utf-8')`
    still guards each match: a triplet that isn't itself valid UTF-8 (the
    third byte outside a continuation shape doesn't reach the regex at all,
    but this keeps the contract explicit) is left exactly as it arrived."""
    def fix(match):
        run = match.group(0)
        try:
            return run.encode("latin-1").decode("utf-8")
        except UnicodeDecodeError:
            return run
    return _MOJIBAKE_PUNCT.sub(fix, text)


def _clean_thinking(prose):
    """The author's own words, tidied but not rewritten: control tokens and fence
    crumbs off, runs of blank lines collapsed, ends trimmed. Never paraphrased
    and never truncated — it is a quotation, and a quotation that has been
    improved is no longer evidence of anything."""
    prose = _repair_mojibake(prose or "")
    prose = _READING.sub("", prose)
    # Only the MARKER lines go, never what stood between them. A block the author
    # quoted mid-thought ("the library's saw idiom is: ```…``` but a struck bar
    # is closer") is part of the sentence; deleting it leaves a sentence with its
    # object missing, presented as a verbatim quotation.
    prose = _FENCE_MARK.sub("", prose)
    prose = prose.replace("```", "")
    prose = _CTRL_TOKEN.sub("", prose)
    prose = _STRAY_CONTROL.sub("", prose)
    prose = "\n".join(ln for ln in prose.splitlines() if not _CHANNEL_NAME.match(ln))
    lines, out, blanks = prose.splitlines(), [], 0
    for ln in lines:
        if ln.strip():
            blanks = 0
            out.append(ln.rstrip())
        else:
            blanks += 1
            if blanks == 1 and out:
                out.append("")
    return "\n".join(out).strip()


def _first_code_run(txt):
    """Character offset where the code starts in an UNFENCED reply, or 0 if it
    starts at the top.

    A RUN of two code lines, not one: "aexc is the bow, continuous noise" is a
    sentence about the code and reads as code to any line matcher, so a
    single-line rule would cut most replies mid-reasoning. Blank lines are
    neutral — they neither start a run nor break one. Same rule the live stream
    uses, so what the panel shows while the author writes and what the compiler
    is finally handed cannot disagree."""
    lines = (txt or "").splitlines(keepends=True)
    run_start, run = None, 0
    at = 0
    for ln in lines:
        stripped = ln.split(";", 1)[0].strip()
        if not stripped:
            at += len(ln)
            continue
        if _codeishness(ln):
            if run == 0:
                run_start = at
            run += 1
            if run >= 2:
                return run_start
        else:
            run, run_start = 0, None
        at += len(ln)
    return 0


def _live_watch(on_thinking, on_body, attempt):
    """Split the author's token stream into THINKING and BODY while it arrives.

    THINKING first, exactly as before: the order HOW TO ANSWER imposes means
    everything up to the first fence marker is reasoning, and it is finished
    before the code starts. The full cleaned text goes out each time, not the
    increment — _clean_thinking edits what it has already seen (a control token
    completes, a run of blank lines collapses), so an appending receiver would
    drift out of step with what the author actually wrote. It is compared for
    DIFFERENCE, not for growth: a revision that shortens the text is the
    correction of something wrong on screen, and a growth test suppresses
    exactly those.

    Nothing is judged until its line is COMPLETE. A fence pattern ends in `$`,
    which matches the end of the buffer as readily as the end of a line, so a
    half-arrived "```mode" reads as a fence that is not there. Working in whole
    lines also keeps this to a few frames a second rather than one per token.

    The BODY (BJ 2026-07-24: minutes of "Writing the instrument" with no sight
    of the token output — and the code IS most of the generation) is found the
    way sanitize() finds it, INCREMENTALLY: the reply is split into segments on
    individual fence-marker lines — never on marker PAIRS, because the author's
    replies are malformed in exactly the ways pairing mis-binds (a stray closer
    above the real block, an unclosed final fence; _fence_segments' own rule) —
    and _pick_body's contract decides which segment is on display: the last one
    with a READING and code, else the most code, ties to the later. A segment
    that never shows code (a prose afterthought) can therefore never replace
    the orchestra on screen, and a stray closer costs nothing because nothing
    assumes it closed anything. What goes out through ``on_body(attempt,
    text)`` is the whole displayed body so far, replace-not-append — the
    thinking's own contract — filtered exactly as sanitize() will filter it
    (READING out, host lines out), so the live view converges on the very code
    the card then carries. tools/lco_sanitize_gate.py asserts that convergence
    over the full malformed-reply corpus, streamed one character at a time.

    With no marker anywhere the body starts at the first RUN of two code lines
    — a run, not a single line, because "aexc is the bow, continuous noise" is
    a sentence about the code and reads as code to any line matcher; blank and
    `;`-comment lines are neutral, exactly as in _first_code_run, so the live
    cut and sanitize's cannot land on different lines.

    The caller must invoke ``watcher.flush()`` once the generation ends: the
    reply's last line has no newline behind it (an unclosed final fence is the
    normal stopped-generation shape), and a line-granular splitter would
    otherwise hold it back forever."""
    if on_thinking is None and on_body is None:
        return None

    def _segment():
        # cut/run/runstart implement _first_code_run incrementally, for the
        # only segment that needs it (the no-marker reply, segment 0).
        return {"lines": [], "code": 0, "reading": False,
                "cut": None, "run": 0, "runstart": None}

    segs = [_segment()]
    state = {"buf": "", "kept": [], "held": [], "closed": False, "sent": None,
             "dirty": False, "body_dirty": False, "body_sent": None}

    def seg_add(line):
        seg = segs[-1]
        seg["lines"].append(line)
        state["body_dirty"] = True
        if _READING.match(line):
            seg["reading"] = True
        # A blank or `;`-only line is NEUTRAL — it neither starts a code run
        # nor breaks one (_first_code_run's rule, verbatim).
        if not line.split(";", 1)[0].strip():
            return
        if _codeishness(line):
            if seg["run"] == 0:
                seg["runstart"] = len(seg["lines"]) - 1
            seg["run"] += 1
            seg["code"] += 1
            if seg["cut"] is None and seg["run"] >= 2:
                seg["cut"] = seg["runstart"]
        else:
            seg["run"], seg["runstart"] = 0, None

    def picked():
        # _pick_body's rule over the segments so far.
        later = range(1, len(segs))
        for i in reversed(later):
            if segs[i]["reading"] and segs[i]["code"]:
                return i
        best = max(later, key=lambda i: (segs[i]["code"], i), default=0)
        return best if (later and segs[best]["code"]) else 0

    def flush_body(final=False):
        if on_body is None or not (state["body_dirty"] or final):
            return
        state["body_dirty"] = False
        i = picked()
        seg = segs[i]
        lines = seg["lines"]
        if i == 0:
            # Segment 0 is DISPLAYED more cautiously than it is finally parsed.
            # sanitize hands the whole pre-marker text to the compiler when
            # nothing after a marker carries code — but WHILE the reply is
            # arriving that same rule would print the reasoning as the
            # instrument, and it would do so at the worst moment: the fence has
            # just opened, its body has not arrived yet, and the panel would
            # show the whole paragraph in monospace under WRITING while the
            # identical text stands under THINKING right above it.
            #
            # So mid-stream segment 0 shows ONLY from a code RUN of its own
            # (_first_code_run's two-line rule — one code-ish line is normal in
            # the reasoning: "attack fast, decay slow" satisfies every
            # shape-based test there is). The run cut governs whether a marker
            # has been seen or not; a marker is the strongest evidence yet that
            # what stands above it was prose, so it must not WEAKEN the guard.
            #
            # At the END the ambiguity is over and sanitize's own reading is
            # the truth: with markers, segment 0 is taken whole; without, from
            # _first_code_run's cut (none found = from the top).
            if not final:
                lines = lines[seg["cut"]:] if seg["cut"] is not None else []
            elif len(segs) == 1 and seg["cut"] is not None:
                lines = lines[seg["cut"]:]
        # sanitize's own steps on its own chosen segment, in its own order, so
        # the live view converges on the card by construction rather than by
        # resemblance: fence crumbs out, the READING line out (its pattern
        # spans the line BREAK when the value sits on the next line, which is
        # why this runs over the joined text and not line by line), then blank
        # lines and the host's own lines out.
        text = _READING.sub("", "\n".join(lines).replace("```", ""))
        shown = [ln.rstrip() for ln in text.splitlines()
                 if ln.strip() and not _STRIP.match(ln)]
        text = "\n".join(shown)
        # Nothing to say yet is not news: the first frames of a generation are
        # reasoning, and an empty body frame there would arrive before any code
        # exists — a wasted frame on the wire, and one that would satisfy a
        # reader checking "did the code stream at all?".
        if text == state["body_sent"] or (not text and state["body_sent"] is None):
            return
        state["body_sent"] = text
        on_body(attempt, text)

    def prose_line(line):
        # The thinking-side rules, unchanged: hold blanks and single code-ish
        # lines, release prose, close on a RUN of two code lines.
        if not line.split(";", 1)[0].strip():
            state["held"].append(line)
            return
        if _codeishness(line):
            state["held"].append(line)
            if sum(1 for h in state["held"] if _codeishness(h)) >= 2:
                state["closed"] = True
            return
        state["kept"].extend(state["held"])
        state["held"].clear()
        state["kept"].append(line)
        state["dirty"] = True

    def take_line(line):
        fence = _FENCE_TAIL.search(line)
        if fence is not None:
            # The fence can open at the END of a sentence; that head belongs to
            # the segment (and the thinking) BEFORE the marker, exactly where
            # _fence_segments' spans put it.
            head = line[:fence.start()].rstrip()
            if head:
                seg_add(head)
            if not state["closed"]:
                if head:
                    state["kept"].extend(state["held"])
                    state["kept"].append(head)
                    state["dirty"] = True
                # Held crumbs before the fence are neither thinking nor body.
                state["held"].clear()
                state["closed"] = True
            segs.append(_segment())
            state["body_dirty"] = True
            return
        seg_add(line)
        if not state["closed"]:
            prose_line(line)

    def on_delta(piece):
        state["buf"] += piece
        while "\n" in state["buf"]:
            line, _, state["buf"] = state["buf"].partition("\n")
            take_line(line)
        flush_body()
        # Recomputed only when the prose actually changed: during the body —
        # the long half of the generation — this would otherwise re-clean the
        # whole unchanged reasoning once per token.
        if state["dirty"] and on_thinking is not None:
            state["dirty"] = False
            text = _clean_thinking("\n".join(state["kept"]))
            if text != state["sent"]:
                state["sent"] = text
                on_thinking(attempt, text)

    def flush():
        # End of generation: the last line arrives with no newline behind it,
        # and the segment-0 fallback (_first_code_run's "no run found means the
        # body IS the whole segment") only exists once the reply is over.
        #
        # A watcher that raises must not cost the authoring: the streaming path
        # already holds that invariant per delta (run_gguf_instruct logs and
        # drops the callback), and this call sits OUTSIDE that guard — a
        # display callback failing here would discard a finished orchestra as
        # an authoring error.
        try:
            if state["buf"]:
                line, state["buf"] = state["buf"], ""
                take_line(line)
            flush_body(final=True)
            if state["dirty"] and on_thinking is not None:
                state["dirty"] = False
                text = _clean_thinking("\n".join(state["kept"]))
                if text != state["sent"]:
                    state["sent"] = text
                    on_thinking(attempt, text)
        except Exception as exc:                    # noqa: BLE001 — see above
            print(f"lco_write: live watcher flush failed, authoring continues: {exc}",
                  file=sys.stderr, flush=True)

    on_delta.flush = flush
    return on_delta


def sanitize(raw):
    """Model reply -> (body, reading, thinking).

    `thinking` is everything the author wrote OUTSIDE the fence. Since the
    author is asked to reason in plain language before writing the orchestra
    (see HOW TO ANSWER), that prose is the one place the machine says WHY this
    code and not other code — and it was being dropped on the floor here. It is
    passed out verbatim so the panel can show it; nothing downstream reads it,
    and it never touches the body or the compile.

    Strips fences, the host's own lines and the READING line; recovers `asig`
    when the model wrote its output through `out`/`outch` under another name."""
    txt = raw or ""
    raw_txt = txt
    thinking = ""

    spans = _fence_segments(txt)
    if len(spans) > 1:
        best = _pick_body([txt[a:b] for a, b, _, _ in spans])
        s0, s1, mark_before, mark_after = spans[best]
        # The thinking is the whole reply MINUS the chosen block and the two
        # markers that delimited it — so every other quoted block survives where
        # the author put it.
        cut0 = mark_before.start() if mark_before is not None else s0
        cut1 = mark_after.end()    if mark_after  is not None else s1
        thinking = _clean_thinking(txt[:cut0] + "\n" + txt[cut1:])
        txt = txt[s0:s1]
    else:
        # No fence anywhere in the reply — and the reasoning is still in front of
        # the code, because that is what HOW TO ANSWER asks for. Without a cut
        # here the paragraph goes to the Csound compiler verbatim, the attempt
        # is burned on a syntax error in an English sentence, and the panel
        # shows no reasoning at all because it was never separated out.
        cut = _first_code_run(txt)
        if cut > 0:
            thinking = _clean_thinking(txt[:cut])
            txt = txt[cut:]
    txt = txt.replace("```", "")

    # The author's own words about what it built. Prefer the one that sits WITH
    # the code: a READING in the thinking is a draft (or, seen in testing, the
    # prompt's own placeholder restated) and must not reach the panel or the
    # re-prompt loop as the machine's reading.
    reading = ""
    rm = _READING.search(txt) or _READING.search(raw_txt)
    if rm:
        # Same author's-words surface as `thinking`, same known corruption —
        # see _repair_mojibake. Not compiler input (that guard is for `txt`
        # below, which stays untouched), so nothing stops applying it here too.
        reading = _repair_mojibake(rm.group(1).strip())
    txt = _READING.sub("", txt)

    kept, captured_out = [], None
    for ln in txt.splitlines():
        s = ln.rstrip()
        if not s.strip():
            continue
        mo = _OUT_CALL.match(s)
        if mo:
            captured_out = mo.group(1)
        if _STRIP.match(s):
            continue
        kept.append(s)
    body = "\n".join(kept)
    # The model routed its signal to the output under another name: keep the
    # sound and give the host the variable it needs.
    if not re.search(r"^\s*asig\b", body, re.MULTILINE) and captured_out and captured_out != "asig":
        body += f"\n  asig = {captured_out}"
    return body, reading, thinking



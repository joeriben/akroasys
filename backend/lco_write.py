def compile_body(body):
    """A body somebody EDITED -> the same {ok, orchestra, error} shape authoring
    returns. No model involved: the user is the author here.

    The host scaffold lives in this module, so a hand-edited body cannot be
    compiled anywhere else — wrapping it in the plugin would mean a second copy
    of `_HEAD`/`_TAIL`/`_SCORE` that drifts from this one, and the drift would
    show up as an orchestra that compiles in the panel and fails in the engine.

    The error is the same _explain() text the author is repaired with, which
    quotes the offending line of the BODY rather than of the wrapped CSD — the
    person editing has never seen the wrapper either."""
    body = (body or "").strip()
    if not body:
        return {"ok": False, "error": "nothing to compile"}
    if _csound_binary() is None and _csound_library() is None:
        return {"ok": False, "error": NO_COMPILER}

    # The person editing is the author now, and the knobs come from the same
    # place: the library parameter lines standing in the text. So editing one
    # line of Csound cannot silently take a slider away, and writing a library
    # line into the editor by hand gives one — the same knobs on the same
    # channels this body had when it was authored, because `read_controls` reads
    # the body and nothing else.
    controls = read_controls(body)
    orchestra = wrap(wire_controls(body, controls), controls)
    try:
        ok, err = syntax_check(orchestra)
    except CompilerUnavailable as exc:
        return {"ok": False, "error": str(exc)}
    if not ok:
        return {"ok": False, "error": err}
    ok, err = perform_check(orchestra)
    if not ok:
        return {"ok": False, "error": err}
    # A hand edit can take a knob's wiring out and leave its line standing, the
    # same way an authoring turn can, and the person editing has exactly the same
    # claim on being told. So the same gate, on the same body.
    orchestra, controls = gate_knobs(body, orchestra, controls)
    return {"ok": True, "orchestra": orchestra, "params_text": body,
            "controls": controls}


def build_csound_response(text, llm, correction="", previous="",
                          on_thinking=None, on_body=None, on_attempt=None,
                          synth_params=None):
    """Prompt -> live Csound orchestra. The REAL pipeline entry
    (pipe_inference mode=="csound" calls this).

    ONE inference writes the orchestra body against the library; the compiler
    checks it; a failure goes back to the model with Csound's own error, up to
    MAX_TRIES. There is NO fallback: if the model cannot produce a compiling
    orchestra, this returns ok=false and the LCO stays silent, exactly as
    docs/LCO_CONCEPT.md §4 requires ("no LLM, no oscillator").

    ``llm`` is the caller-injected ``(text, system_prompt, max_new_tokens) ->
    str`` callable. Returns the {ok, orchestra, reading, error} shape the C++
    PipeInference parses.

    ``correction``/``previous`` are accepted for wire compatibility and are
    appended to the user turn when present (the self-listen loop is currently
    deactivated and sends neither).

    ``on_thinking(attempt, text)`` is optional and, when given, is called with
    the author's reasoning WHILE it is being written — the attempt number rides
    along because a repair starts the reasoning over and whoever is showing it
    has to start over too. It is passed on only if ``llm`` was built to take it;
    the returned response is the same either way.

    ``on_body(attempt, text)`` is the same contract for the CODE — the whole
    body written so far, replace-not-append. It exists because the code is most
    of the generation: without it the panel goes dark the moment the reasoning
    ends and stays dark for minutes (BJ 2026-07-24).

    ``on_attempt(attempt, max_tries, errors)`` fires when a REPAIR round
    starts, before its inference — the attempt number, the ceiling, and every
    distinct compiler error the author is being shown. Without it the repair
    loop is invisible while it runs: each round is a full regeneration, and the
    panel would sit on attempt 1's caption throughout.
    """
    prompt = (text or "").strip()
    if not prompt:
        return {"ok": False, "error": "empty prompt"}

    # Ask once, before spending inferences: with nothing to compile against,
    # every attempt would fail identically at the gate, and the honest answer is
    # already available. An uncapped 12B authoring turn is not cheap enough to
    # burn six of on a question the environment has already answered.
    if _csound_binary() is None and _csound_library() is None:
        return {"ok": False, "error": NO_COMPILER}

    user_turn = prompt
    if correction:
        user_turn = (f"{prompt}\n\nThe previous attempt was described as: "
                     f"{previous}\nCorrect it: {correction}")

    # THE CONSULTATION IS THE AUTHOR'S, NOT PYTHON'S. The system prompt carries
    # the library INDEX — every entry and what its parameters do, no code. The
    # author reads the shelf, reasons about the sound, and names what it wants
    # opened; `_consult` runs that turn and `open_entries` fetches exactly what
    # it named. Python recognises names, it does not choose.
    #
    # What this replaces: `select(prompt)` compared the USER's words against the
    # lexicon's surface forms and quoted the entries that matched, topped up from
    # a fixed starter set. That put a word comparison between a person's
    # description and the library, with a word matcher's holes — "bell" hit,
    # "bells" did not, German nothing — and it decided deterministically what the
    # author was allowed to see. BJ, 2026-07-24, standing rule: "es ist mir
    # strikt untersagt das LLM deterministisch einzuschränken, egal in welcher
    # Form", and on how the consultation must work instead: "Es geht eine Liste
    # mit Instrumenten und sonischen Beschreibungen der Parameter in den Prompt.
    # Thinking wird dann nicht-deterministisch entscheiden was im nächsten Zug
    # dem LLM aus der Bibliothek zur Verfügung gestellt wird."
    # The synth's own knobs ride in the SAME system prompt as the library,
    # for the same reason: the author sees the whole shelf once and decides
    # for itself. Absent unless the player allowed it, in which case the
    # author is never told these controls exist.
    sysp = system_prompt(params=synth_params)
    consult_raw, named, consult_thinking = _consult(user_turn, sysp, llm, on_thinking)
    sel = open_entries(named)
    attempts = []
    seen_errors = []   # distinct errors, in first-seen order — the whole repair context
    # The writing turn CONTINUES the consultation: the author's own choice stays
    # in the conversation, so the pages arrive as an answer to what it asked for
    # rather than as a fresh instruction it has to re-motivate.
    base = [{"role": "user", "content": user_turn},
            {"role": "assistant", "content": consult_raw},
            {"role": "user", "content": _writing_turn(sel)}]
    if not getattr(llm, "accepts_messages", False):
        base = _flatten_turn(base)
    turn = base
    # A repair CONTINUES the conversation instead of starting it over. Handing
    # the author only the errors and the original prompt made every retry a
    # fresh authoring: it re-derived the instrument, re-decided the movement and
    # re-wrote its whole reasoning paragraph before it got anywhere near the one
    # broken line — the thinking visibly restarting from zero on screen each
    # time (BJ 2026-07-24: "bei jedem Scheitern startet der KOMPLETTE Prozess
    # neu inkl. thinking. Das ist ineffizient"). With its own previous answer in
    # the turn it fixes what the compiler named and keeps the rest, and the
    # reasoning it already did stays valid instead of being generated again.
    # `_repair_turn` still shows EVERY distinct error at once, so the 2-cycle it
    # was written against (fix A, break B, fix B, reintroduce A) stays closed.
    prev_raw = ""          # the author's own last reply, quoted back to it
    last_raw = None        # the one before that — a repeat means the loop is stuck
    tried = 0              # what actually ran, which the early stop makes < MAX_TRIES
    # An orchestra that COMPILES AND PLAYS but hands the player a stripped part
    # (`frozen_controls`). It goes back for repair like any other error, and this
    # holds it so the sound cannot be lost to a verdict about the panel — the
    # same order of precedence `gate_knobs` already keeps.
    spare = None

    def _respond(orchestra, controls, body, reading, raw, attempt, thinking,
                 extra_refused=()):
        """The success payload the C++ side parses. One place, because the spare
        above returns through here too and the two must not drift apart."""
        if extra_refused:
            controls = dict(controls)
            controls["refused"] = list(controls.get("refused", ())) + list(extra_refused)
        return {"ok": True, "orchestra": orchestra,
                "reading": reading or _fallback_reading(body),
                # What the author asked the SYNTH to set, checked against the
                # shelf that was sent with the request. Empty list when the
                # player did not allow it (no shelf was sent, so the author was
                # never told the controls exist) or when it wanted nothing out
                # there.
                "settings": read_settings(raw, synth_params),
                # The knobs THIS body gives the player: `parts` are the columns
                # — one per library entry it drew a parameter line from —
                # `params` the sliders, `refused` every line that was not the
                # library's to give. The panel shows exactly this and invents
                # nothing (§1 of docs/plans/PLAN_lro_param_panel.md).
                "controls": controls,
                # The panel's transparency surface. Under the write-path the
                # honest answer to "what did the machine build?" is the code the
                # model actually wrote -- not a list of keys it picked, because
                # it picks none. UNWIRED, which is also the shape a person can
                # edit: each knob stands in it as the library's own line, a
                # number with its name and range beside it, and `compile_body`
                # reads the knobs back out of exactly this text. The `kp` wiring
                # is the host's and belongs to the orchestra, not the authorship.
                "params_text": body,
                # The author's own reasoning, verbatim: the plain-language
                # paragraph HOW TO ANSWER asks for BEFORE the fence -- what it
                # decided this sound is, what excites and resonates in it, what
                # moves. It was being discarded here, which made the one place
                # the machine says WHY this code invisible. Nothing downstream
                # reads it; it never touches the body, the reading or the
                # compile. From the SUCCESSFUL attempt, so it explains the
                # orchestra that is actually running.
                "thinking": thinking,
                # The rest of the authoring trace, so the panel can show HOW this
                # orchestra came about and not only WHAT came out. Every field is
                # a record of what actually happened; nothing is composed on the
                # author's behalf (BJ 2026-07-24: "nur was ohnehin passiert ist").
                "consultation": sel["consultation"],
                # The compiler errors this body had to be repaired past, in
                # first-seen order; empty when it compiled on the first try.
                # Shown, not hidden: an orchestra that took four rounds to stand
                # up is a different fact about the machine than one that landed
                # immediately, and only the panel can say so.
                "repairs": list(seen_errors),
                "attempts": attempt}
    # The reasoning is written ONCE — in the consultation, which is the turn
    # that is nothing but reasoning — and stays the answer. The writing turn is
    # explicitly asked not to reason again, so without this seed the panel's
    # THINKING would be empty for every orchestra the two-turn path produces.
    first_thinking = consult_thinking or ""
    for attempt in range(1, MAX_TRIES + 1):
        # The panel's only sight of the repair loop: which round is starting
        # and what it was sent back for. BEFORE the inference, because the
        # round is a full body regeneration — minutes that would otherwise
        # still be captioned as attempt 1.
        tried = attempt
        if attempt > 1 and on_attempt is not None:
            on_attempt(attempt, MAX_TRIES, list(seen_errors))
        # No token cap: the orchestra is as long as the sound needs. A cap here
        # would cut the body mid-line, and a truncated generation is not an
        # error — it would arrive as a syntax failure with no cause to show.
        # The fourth argument only exists when someone is watching: the offline
        # callers inject a three-argument llm and must keep working untouched.
        watcher = _live_watch(on_thinking, on_body, attempt)
        # A conversation only goes out to a surface that says it takes one.
        # Offline callers inject a plain `(text, system, max) -> str`; handing
        # one of those a message list would fail deep inside somebody else's
        # code, so the capability is DECLARED (`llm.accepts_messages`) rather
        # than guessed at from an exception.
        sent = turn if getattr(llm, "accepts_messages", False) else _flatten_turn(turn)
        raw = llm(sent, sysp, None) if watcher is None else llm(sent, sysp, None, watcher)
        if watcher is not None:
            # The reply's last line has no newline behind it (an unclosed final
            # fence is the normal stopped-generation shape) — release it, or
            # the panel ends one line short of the code the card then carries.
            watcher.flush()
        body, reading, thinking = sanitize(raw)
        # The reasoning belongs to the SOUND, not to the attempt that finally
        # compiled. A repair is asked not to reason again, so a repaired
        # orchestra would otherwise carry no reasoning at all -- the panel would
        # go blank for exactly the sounds that were hardest to write.
        if thinking.strip() and not first_thinking:
            first_thinking = thinking
        prev_raw = raw
        if not body.strip():
            attempts.append("the model returned no code")
            if "you returned no code at all" not in seen_errors:
                seen_errors.append("you returned no code at all")
            turn = _continue(base, prev_raw, seen_errors)
            continue

        # The knobs BEFORE the compile, because they are part of what compiles:
        # the wiring rewrites the body's own lines, and their starting values are
        # the head's `chnset` lines — so what is checked is the wired orchestra
        # at the position the author put each knob, not a different body at 0.5.
        controls = read_controls(body)
        orchestra = wrap(wire_controls(body, controls), controls)
        try:
            ok, err = syntax_check(orchestra)
        except CompilerUnavailable as exc:
            # The compiler went away mid-run (or could not be spawned). Stop:
            # re-prompting the author with an environment fault would ask it to
            # repair code that may be perfectly good, five more times.
            return {"ok": False, "error": str(exc), "attempts": attempt}
        if ok:
            # …and does it play? A body that only parses can still be silence
            # (see `perform_check`), and silence that reports success is the one
            # failure the repair loop can neither see nor answer.
            ok, err = perform_check(orchestra)
        if ok:
            # …and is every part still an instrument? A control frozen to a
            # constant leaves its variable standing with nothing reading it, and
            # that is a PART stripped of an axis the user named — measured on
            # "a vibraphone > a saw wave", where the saw end arrived as a single
            # `vco2` under a dead `kwave0` and the panel showed one slider where
            # the entry has five. It goes back to the author like a compiler
            # error, because it is one the compiler cannot see. It never costs
            # the SOUND: `spare` keeps this orchestra, and if the rounds run out
            # it is what comes back, with the finding beside its knobs.
            frozen = frozen_controls(body)
            if frozen:
                if spare is None:
                    spare = (orchestra, controls, body, reading, raw, attempt)
                ok = False
                err = ("dead code: " + ", ".join(frozen) + " — set to a constant "
                       "and read by nothing. A control frozen to a number is a "
                       "part stripped of an axis; build that part in full and "
                       "let its own parameter lines drive it")
        if ok:
            # …and does every knob it hands the player do anything? The last
            # gate, because it is the only one that costs a render per knob, and
            # the only one whose verdict is about the PANEL rather than about
            # whether the orchestra stands up (`gate_knobs`).
            orchestra, controls = gate_knobs(body, orchestra, controls)
            return _respond(orchestra, controls, body, reading, raw, attempt,
                            first_thinking or thinking)
        attempts.append(err)
        n_before = len(seen_errors)
        if err not in seen_errors:
            seen_errors.append(err)
        # A repair round is a function of exactly three things: the request, the
        # author's last answer and the errors so far. When an attempt reproduces
        # the previous answer AND raises nothing new, the next round's input is
        # identical to this one's — and a greedy decoder given identical input
        # returns identical output. The remaining attempts cannot differ; they
        # can only cost. Measured on "accordeon > guitar": attempts 3 to 6 were
        # byte-identical, four inferences of ~50 s each spent re-deriving a
        # fixed point. Stopping there does not lose a repair that would have
        # happened; it declines to buy the same one four more times.
        if raw == last_raw and len(seen_errors) == n_before:
            break
        last_raw = raw
        turn = _continue(base, prev_raw, seen_errors)

    # The rounds ran out, and one of them left an orchestra that compiles and
    # plays and is only guilty of a stripped part. That sound wins over the
    # verdict: the player gets the instrument, and what was measured travels with
    # it in `refused`, where the panel already shows what a knob did not become.
    if spare is not None:
        orchestra, controls, body, reading, raw, attempt = spare
        orchestra, controls = gate_knobs(body, orchestra, controls)
        return _respond(orchestra, controls, body, reading, raw, attempt,
                        first_thinking,
                        [f"{n} — frozen to a constant and read by nothing; the "
                         f"part it belongs to was not built in full, and "
                         f"{MAX_TRIES} rounds did not get it back"
                         for n in frozen_controls(body)])

    # Report every DISTINCT error, not just the last one. The two cases look the
    # same from outside and need opposite responses: six times the same complaint
    # is the library orienting the author wrongly and is fixable here; six
    # different ones is a prompt this author cannot hold together. With only the
    # last error visible, a systematic gap reads as bad luck.
    seen, distinct = set(), []
    for e in attempts:
        if e not in seen:
            seen.add(e)
            distinct.append(e)
    if not distinct:
        detail = "unknown"
    elif len(distinct) == 1:
        detail = f"the same error every time: {distinct[0]}"
    else:
        detail = " | ".join(distinct)
    # The number of attempts that actually RAN, not the ceiling. The early stop
    # above leaves the loop before MAX_TRIES, and reporting the ceiling anyway
    # tells the user (and the trace's REPAIRED station) that six authoring rounds
    # were spent when three were — which is both false and the wrong diagnosis:
    # "six times the same complaint" and "it stopped repeating after three" are
    # different situations. Observed exactly so on "bright shimmer degrading to a
    # dark rumble": three inferences, reported as six.
    return {"ok": False,
            "error": f"the author could not write a compiling orchestra after "
                     f"{tried} attempt{'' if tried == 1 else 's'}: {detail}",
            "attempts": tried}


def _fallback_reading(body):
    """A reading when the model omitted its READING line. Names the opcodes it
    actually used — a true, if plain, statement about what is running."""
    seen = []
    for op in ("vco2", "foscili", "gbuzz", "buzz", "mode", "oscili", "phasor",
               "rand", "reson", "tablei", "tanh", "balance"):
        if re.search(rf"\b{op}\b", body) and op not in seen:
            seen.append(op)
    return ("built from " + ", ".join(seen[:5])) if seen else "authored orchestra"

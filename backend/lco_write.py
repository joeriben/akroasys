# The host scaffold — everything around the authored body
# ─────────────────────────────────────────────────────────────────────────────
# Unchanged from the shipped contract: sr is substituted by the engine at its
# real rate, ksmps=64, nchnls=16 (one channel per voice), one numeric `instr 1`
# with p4 = voice index, six named control channels per voice read via chnget,
# and 16 always-on score instances.

_HEAD = (
    "<CsoundSynthesizer>\n<CsOptions>\n-n -d\n</CsOptions>\n<CsInstruments>\n"
    "sr = %SR%\n"
    f"ksmps = {KSMPS}\n"
    f"nchnls = {NCHNLS}\n"
    "0dbfs = 1\n"
    "giSine ftgen 1, 0, 65536, 10, 1\n"
    # gbuzz reads a COSINE table (its harmonics are cosines); a sine table here
    # would phase-shift every harmonic against the fundamental.
    "giCos  ftgen 2, 0, 65536, 11, 1\n"
    # GEN13 Chebyshev TRANSFER function, odd harmonics with alternating signs:
    # odd-only is antisymmetric, so f(0)=0 and the shaper is DC-free at EVERY
    # drive level and can be swept freely; alternating signs leave each
    # harmonic's magnitude untouched (a sign is a phase) while the peak sums to
    # 0.71 instead of 2.01 — 10 dB of crest given back.
    "giCheb ftgen 3, 0, 8193, 13, 1, 1, 0, 1, 0, -0.5, 0, 0.28, 0, -0.15, 0, 0.08\n"
    # Short decaying harmonic burst: the mallet contact for struck models, which
    # take their strike argument as a TABLE NUMBER, not a scalar.
    "giImp  ftgen 4, 0, 256, 10, 1, 0.5, 0.3, 0.2, 0.1\n"
    # Starting values for the player's mix/octave knobs. The three `oscNvol`
    # channels ARE driven from the plugin — processBlock writes them every
    # block from the panel's layer levels, alongside the twelve knob channels —
    # so what stands here is only where they start. The three `oscNoct` are not
    # written by anything today, so for those the head's value is all they ever
    # carry and is what the running instrument transposes by.
    "chnset 1.0000, \"osc1vol\"\n"
    "chnset 1.0000, \"osc1oct\"\n"
    "chnset 1.0000, \"osc2vol\"\n"
    "chnset 1.0000, \"osc2oct\"\n"
    "chnset 1.0000, \"osc3vol\"\n"
    "chnset 1.0000, \"osc3oct\"\n"
    # The twelve player knobs for this body. Always all twelve, always in this
    # order, whatever the body carries: the head keeps one shape, _BODY_OFFSET
    # stays a constant, and the host resolves twelve channel pointers once
    # instead of after every authoring. `wrap` substitutes the starting value of
    # each knob that was wired; the rest stay at LRO_DEFAULT and are read by
    # nothing.
    + "".join(f"chnset %LRO{c.upper()}%, \"lroP{c}\"\n" for c in LRO_CHANNELS) +
    "\n"
    "instr 1\n"
    "  ivoice   = p4\n"
    "  Sgate    sprintf \"gate%d\", ivoice\n"
    "  Sfreq    sprintf \"freq%d\", ivoice\n"
    "  Svel     sprintf \"vel%d\", ivoice\n"
    "  Spres    sprintf \"pres%d\", ivoice\n"
    "  Stimb    sprintf \"timb%d\", ivoice\n"
    "  Strig    sprintf \"trig%d\", ivoice\n"
    "  kgateraw chnget Sgate\n"
    "  kfreqraw chnget Sfreq\n"
    "  kvel     chnget Svel\n"
    "  kpres    chnget Spres\n"
    "  ktimb    chnget Stimb\n"
    "  ktrig    chnget Strig\n"
    "  kvol1    chnget \"osc1vol\"\n"
    "  koct1    chnget \"osc1oct\"\n"
    "  kvol2    chnget \"osc2vol\"\n"
    "  koct2    chnget \"osc2oct\"\n"
    "  kvol3    chnget \"osc3vol\"\n"
    "  koct3    chnget \"osc3oct\"\n"
    + "".join(f"  kp{c:<7} chnget \"lroP{c}\"\n" for c in LRO_CHANNELS) +
    "  kgate    portk kgateraw, 0.001\n"
    "  kfreq    limit kfreqraw, 20, 12000\n"
    "  kpresGain = 1.0 + 0.15 * kpres\n"
    # Seconds since THIS note, for anything that shapes timbre over the note.
    # init 0 rather than a settled value: a note whose gate and trig are already
    # high before the first k-cycle gives changed2 no edge to fire on, so a
    # counter starting anywhere else would sit frozen forever.
    "  knote    init 0\n"
    "  if changed2(ktrig) == 1 then\n"
    "    knote  = 0\n"
    "  endif\n"
    "  knote    = knote + 1/kr\n\n"
)

_TAIL = (
    "\n"
    # kvel deliberately absent (BJ 2026-07-25): the voice envelope's peak
    # already tracks velocity (velPeakScale), so a kvel factor here made the
    # LRO scale as vel^2 where every other engine is linear — measured peak
    # ratio 100:30 = 10.9 against the sampler's 3.33. One loudness (§4): the
    # player's envelope owns it. kvel stays in scope for the AUTHOR (a body
    # may voice velocity as timbre); the host tail must not spend it again.
    f"  aout     = asig * kgate * kpresGain * {HEADROOM}\n"
    "  aout     clip aout, 0, 0.95, 0.85    ; final soft peak safety: transparent\n"
    "                                       ; below ~0.8, asymptotes ~0.88 above,\n"
    "                                       ; bounds ANY op stack / crest / host gain\n"
    "  outch    ivoice, aout\n"
    "endin\n"
    "</CsInstruments>\n<CsScore>\n"
)

# _SCORE_LIFETIME: per-voice score duration in seconds, ~63 years and
# deliberately < INT32_MAX so no parse path can overflow. The previous
# 360000 s (100 h) ENDED the performance in long-running sessions —
# csoundPerformKsmps then returns non-zero forever and spout freezes on its
# last block (measured 2026-08-06 on the bundled CsoundLib64), which the
# host loops as a standing buzz mid-note or permanent silence when idle,
# until the next recompile. A held note (`i 1 0 -1`) does NOT survive —
# measured, the performance ends immediately. Stored presets carry the full
# CSD with the old score; CsoundEngine::prepare() substitutes those at load
# (substituteScoreLifetime).
_SCORE_LIFETIME = 2000000000

_SCORE = "".join(f"i 1 0 {_SCORE_LIFETIME} {v}\n" for v in range(1, NCHNLS + 1)) \
         + f"e {_SCORE_LIFETIME}\n</CsScore>\n</CsoundSynthesizer>\n"


def bake_knob_defaults(head, controls=None):
    """Put the knob starting values into the head's twelve `chnset` lines.

    `controls` is `read_controls`'s result, or None. THE HEAD IS NOT VALID CSOUND
    UNTIL THIS HAS RUN: it carries `%LRO1A%`-style placeholders, and Csound's
    parser stops at the `%`. So every path that builds an orchestra out of `_HEAD`
    goes through here — `wrap` for the engine, `lco_measure.scaffold` for every
    offline measurement — and there is no second copy of the substitution to fall
    behind this one. It was written twice for one afternoon and the measuring side
    was the copy that did not exist, which took out every offline render at once.

    A channel no knob was wired to keeps LRO_DEFAULT, which is what the body's own
    unwired lines were left at, so an offline render plays the sound the author
    described with every knob where the author put it. The plugin overwrites all
    twelve from its own parameters on the next block.

    EVERY DIGIT, because this number is not a display. What stands in the body is
    `lo + span * kp`, so a position written to four decimals comes back as the
    author's number to four decimals TIMES THE SPAN, and the span is not always
    one: `age [0..3] = 1.00` becomes 0.3333, `3 * 0.3333` is 0.9999, and the
    body's own `int(kage)` then reads 0 where the author wrote 1 — a whole step
    of a five-step axis, gone, in a render that is supposed to BE the author's
    sound. Eight of the library's own lines land off their number this way,
    `fm3`'s `ratio 3 = 6` among them, whose gloss reads "a whole number is
    harmonic, between them not". At full precision the round trip is exact to
    the last bit a double holds, and the plugin's own float32 parameter is then
    the only rounding left."""
    values = {p["ch"]: p["value"] for p in (controls or {}).get("params", [])}
    for c in LRO_CHANNELS:
        head = head.replace(f"%LRO{c.upper()}%",
                            f"{values.get(f'lroP{c}', LRO_DEFAULT):.17g}")
    return head


def wrap(body, controls=None):
    """Authored body -> the full orchestra the engine compiles."""
    head = bake_knob_defaults(_HEAD, controls)
    indented = "\n".join(("  " + l) if not l.startswith(" ") else l
                         for l in body.splitlines())
    return head + indented + _TAIL + _SCORE


